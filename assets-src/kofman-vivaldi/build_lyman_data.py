"""DeepStateMap snapshots -> generated/components/kofman-vivaldi/lymanFrontData.ts (world px, 40 px per km).
Run: uv run --with shapely --with pyproj --with pyshp python assets-src/kofman-vivaldi/build_lyman_data.py
Sources: DeepStateMap history API (https://deepstatemap.live/api/history/<id>/geojson):
  20240601 = 1717225039, 20260815 = 1786809894, 20261015 = 1792097671, 20261103 = 1793717237.
Rivers: Natural Earth 10m rivers_lake_centerlines (public domain). Places: OpenStreetMap Nominatim (ODbL)."""
import json, math, os
import shapefile
from shapely.geometry import shape, box, LineString, MultiLineString, mapping
from shapely.ops import unary_union
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "../../generated/components/kofman-vivaldi/lymanFrontData.ts")
LON0, LAT0, PXKM = 37.85, 49.10, 40.0
KX = math.cos(math.radians(LAT0)) * 111.32 * PXKM
KY = 110.57 * PXKM
CLIP = box(36.9, 48.55, 38.9, 49.7)
def P(lon, lat): return (540 + (lon - LON0) * KX, 960 - (lat - LAT0) * KY)
def layer(tag, keys):
    d = json.load(open(os.path.join(HERE, f"deepstate_{tag}.geojson")))
    g = [shape(f["geometry"]).buffer(0) for f in d["features"] if f["geometry"]["type"] in ("Polygon", "MultiPolygon")
         and any(k in f["properties"].get("name", "") for k in keys)]
    return unary_union(g).intersection(CLIP)
def to_px(g):
    from shapely import transform
    return transform(g, lambda c: __import__("numpy").array([P(x, y) for x, y in c]))
def pathd(g, tol=3.0, closed=True, min_area=200.0):
    g = to_px(g).simplify(tol, preserve_topology=True)
    out = []
    polys = [g] if g.geom_type == "Polygon" else list(getattr(g, "geoms", []))
    if closed:
        for p in polys:
            if p.geom_type != "Polygon" or p.area < min_area: continue
            for ring in [p.exterior, *p.interiors]:
                cs = list(ring.coords)
                out.append("M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in cs[:-1]) + " Z")
    else:
        lines = [g] if g.geom_type == "LineString" else list(getattr(g, "geoms", []))
        for l in lines:
            if l.length < 40: continue
            out.append("M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in l.coords))
    return " ".join(out)
def front(tag, keys=("Occupied", "Unknown")):
    a = layer(tag, list(keys))
    edge = a.boundary.difference(CLIP.exterior.buffer(0.003))
    return edge
def main_line(g):
    """The longest single piece of a front, merged, as a TS array of [x, y] world px."""
    from shapely.ops import linemerge
    g = to_px(g)
    m = linemerge(g) if g.geom_type == "MultiLineString" else g
    parts = [m] if m.geom_type == "LineString" else list(m.geoms)
    l = max(parts, key=lambda q: q.length).simplify(3.0)
    cs = list(l.coords)
    if cs[0][1] > cs[-1][1]: cs = cs[::-1]  # north (top) first
    return "[" + ", ".join(f"[{x:.1f}, {y:.1f}]" for x, y in cs) + "]"
occ = {t: layer(t, ["Occupied"]) for t in ["20240601", "20260815", "20261015", "20261103"]}
grey = {t: layer(t, ["Unknown"]) for t in ["20240601", "20260815", "20261015", "20261103"]}
held = {t: unary_union([occ[t], grey[t]]) for t in occ}
retaken = held["20260815"].difference(held["20261015"]).intersection(box(37.3, 48.75, 38.6, 49.5))
retaken = unary_union([g for g in getattr(retaken, "geoms", [retaken]) if g.area > 1e-5])
sf = shapefile.Reader(os.path.join(HERE, "../robert-johnson-ranch/naturalearth/ne_10m_rivers_lake_centerlines/ne_10m_rivers_lake_centerlines"))
rivers = []
for s, r in zip(sf.shapes(), sf.records()):
    g = shape(s.__geo_interface__)
    if g.intersects(CLIP): rivers.append((r.as_dict().get("name") or "", g.intersection(CLIP)))
places = {"Lyman": (37.8168, 48.9801), "Siversk": (38.0902, 48.8676), "Yarova": (37.6395, 49.0600),
          "Serednie": (37.7047, 49.1197), "Zelena Dolyna": (37.8096, 49.1294), "Kolodiazi": (37.8815, 49.0831)}
def area_km2(g):
    from pyproj import Geod
    return abs(Geod(ellps="WGS84").geometry_area_perimeter(g)[0]) / 1e6
rc = to_px(retaken).centroid
L = ["// GENERATED by assets-src/kofman-vivaldi/build_lyman_data.py — do not hand-edit.",
     "// Lyman sector, northern Donetsk Oblast. World px, 40 px per km, local equirectangular at 37.85E 49.10N",
     "// (world (540, 960) = 37.85E 49.10N). North up. Source: DeepStateMap (deepstatemap.live) history snapshots",
     "// 1 Jun 2024, 15 Aug 2026, 15 Oct 2026, 3 Nov 2026. OCC = 'Occupied', GREY = 'Unknown status' (the grey zone),",
     "// FRONT = edge of HELD (west edge of the grey zone); FRONTOCC = edge of OCC only (east edge of the grey zone).\n// HELD = OCC + GREY. RETAKEN_VIVALDI = HELD 15 Aug 2026 minus HELD 15 Oct 2026, inside lon 37.3-38.6 lat 48.75-49.5",
     f"// = {area_km2(retaken):.0f} km2 by DeepState (3rd Army Corps claims 277 km2, 14 Oct 2026).",
     "// Rivers: Natural Earth 10m (PD). Places: OpenStreetMap Nominatim.",
     f"export const PX_PER_KM = {PXKM};",
     "export const LON0 = 37.85, LAT0 = 49.1;",
     f"export const project = (lon: number, lat: number): [number, number] => [540 + (lon - LON0) * {KX:.4f}, 960 - (lat - LAT0) * {KY:.4f}];"]
for t in occ:
    L.append(f'export const OCC_{t} = "{pathd(occ[t])}";')
    L.append(f'export const GREY_{t} = "{pathd(grey[t], tol=2.0, min_area=60)}";')
    L.append(f'export const HELD_{t} = "{pathd(held[t])}";')
    L.append(f'export const FRONT_{t} = "{pathd(front(t), closed=False)}";')
    L.append(f'export const FRONTOCC_{t} = "{pathd(front(t, ("Occupied",)), closed=False)}";')
    L.append(f"// the longest merged piece of FRONT / FRONTOCC, north end first, world px:")
    L.append(f"export const MAINFRONT_{t}: [number, number][] = {main_line(front(t))};")
    L.append(f"export const MAINFRONTOCC_{t}: [number, number][] = {main_line(front(t, ('Occupied',)))};")
L.append(f'export const RETAKEN_VIVALDI = "{pathd(retaken, tol=2.0)}";')
L.append(f"export const RETAKEN_CENTROID: [number, number] = [{rc.x:.1f}, {rc.y:.1f}];")
L.append(f"export const RETAKEN_BOUNDS = {{ x0: {to_px(retaken).bounds[0]:.1f}, y0: {to_px(retaken).bounds[1]:.1f}, x1: {to_px(retaken).bounds[2]:.1f}, y1: {to_px(retaken).bounds[3]:.1f} }};")
L.append(f"export const RETAKEN_KM2_DEEPSTATE = {area_km2(retaken):.0f};")
L.append("export const RIVERS: { name: string; d: string }[] = [")
for n, g in rivers:
    d = pathd(g, closed=False)
    if d: L.append(f'  {{ name: {json.dumps(n)}, d: "{d}" }},')
L.append("];")
L.append("export const PLACES: Record<string, [number, number]> = {")
for n, (lon, lat) in places.items():
    x, y = P(lon, lat); L.append(f'  {json.dumps(n)}: [{x:.1f}, {y:.1f}],')
L.append("};")
for t in occ:
    L.append(f"// grey zone {t}: {area_km2(grey[t].intersection(box(37.3,48.75,38.6,49.5))):.0f} km2 in lon 37.3-38.6 lat 48.75-49.5")
open(OUT, "w").write("\n".join(L) + "\n")
print("wrote", OUT, os.path.getsize(OUT), "bytes; retaken", round(area_km2(retaken)), "km2; centroid", rc)
