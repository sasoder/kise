#!/usr/bin/python3
"""make_paper_tile.py - the newsprint fibre tile of sam-navier-stokes cut 1 (HundredthOfTheCost).

A seamless 768 x 768 MULTIPLY tile (white = no change) laid over the cream page: a faint low-frequency mottle
(+-1 %, periodic FFT noise) and ~2600 short paper fibres (1.5-4 % darker, wrapped across the tile's edges so it
repeats without a seam). Deterministic (seed 7). No halftone: the stout grain on twos already gives the print tooth.
Outputs (overwritten):
  public/sam-navier-stokes/paper_fibre_tile.jpg                 the tile
  generated/components/sam-navier-stokes/paperData.ts           the same JPEG as a data: URL (it is drawn inside the
                                                                StoutStage SVG: CRAFT "Bitmaps inside an SVG")
Run from the kise root:  /usr/bin/python3 assets-src/sam-navier-stokes/make_paper_tile.py
"""
import base64
import io
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
OUT_JPG = ROOT / "public/sam-navier-stokes/paper_fibre_tile.jpg"
OUT_TS = ROOT / "generated/components/sam-navier-stokes/paperData.ts"
N = 768
SS = 2  # supersampling for the fibres
rng = np.random.default_rng(7)

# periodic mottle: band-limited noise through the FFT (periodic by construction)
f = np.fft.fftfreq(N)
fx, fy = np.meshgrid(f, f)
r = np.sqrt(fx**2 + fy**2)
spec = (rng.normal(size=(N, N)) + 1j * rng.normal(size=(N, N))) * np.exp(-((r / 0.012) ** 2))
spec[0, 0] = 0
mottle = np.real(np.fft.ifft2(spec))
mottle = mottle / np.abs(mottle).max()
fine = np.real(np.fft.ifft2((rng.normal(size=(N, N)) + 1j * rng.normal(size=(N, N))) * np.exp(-((r / 0.08) ** 2)) * (r > 0)))
fine = fine / np.abs(fine).max()
base = 1.0 - 0.010 * (0.5 + 0.5 * mottle) - 0.006 * (0.5 + 0.5 * fine)

# fibres, drawn supersampled with wrap-around
M = N * SS
fib = Image.new("L", (M, M), 255)
d = ImageDraw.Draw(fib)
for _ in range(2600):
    x, y = rng.uniform(0, M, 2)
    L = rng.uniform(10, 64) * SS
    ang = rng.uniform(0, np.pi)
    bend = rng.uniform(-0.5, 0.5)
    dark = rng.uniform(0.015, 0.04)
    w = max(1, int(round(rng.uniform(0.6, 1.3) * SS)))
    pts = []
    for t in np.linspace(-0.5, 0.5, 9):
        a = ang + bend * t
        pts.append((x + np.cos(a) * L * t, y + np.sin(a) * L * t))
    v = int(round(255 * (1 - dark)))
    for ox in (-M, 0, M):
        for oy in (-M, 0, M):
            d.line([(px + ox, py + oy) for px, py in pts], fill=v, width=w)
fibres = np.asarray(fib.resize((N, N), Image.LANCZOS)).astype(np.float64) / 255.0

tile = np.clip(base * fibres, 0, 1)
# a warm cast: fibres are a touch browner than grey (multiply keeps the page's hue)
rgb = np.dstack([tile ** 0.9, tile ** 1.0, tile ** 1.25])
img = Image.fromarray((rgb * 255).round().astype(np.uint8))
OUT_JPG.parent.mkdir(parents=True, exist_ok=True)
img.save(OUT_JPG, quality=90)
buf = io.BytesIO()
img.save(buf, format="JPEG", quality=90)
b64 = base64.b64encode(buf.getvalue()).decode("ascii")
OUT_TS.write_text(
    "// paperData - the newsprint fibre tile of sam-navier-stokes cut 1, inlined as a data: URL (CRAFT \"Bitmaps inside\n"
    "// an SVG\"). GENERATED by assets-src/sam-navier-stokes/make_paper_tile.py. Do not edit by hand; rerun the script.\n"
    f"export const PAPER_TILE = {N};\n"
    f"export const PAPER_SRC = \"data:image/jpeg;base64,{b64}\";\n"
)
print(f"tile {N}x{N}, mean {tile.mean():.4f}, min {tile.min():.3f}, data {len(b64) / 1024:.0f} KB")
