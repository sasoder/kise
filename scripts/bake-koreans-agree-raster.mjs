/* global console */
// Bakes ONE extra close level of the shared static Korea map for KoreansAllAgree
// (Sheppard cut D), whose camera lands on the Military Demarcation Line at k ~5,
// past the shared pyramid's sharp limit (close level, k ~3.4). The same stack,
// order, weights and palette as scripts/bake-korea-rasters.mjs (copied, not
// imported: importing it would re-bake the shared levels), at kBake 4.6 and
// 6 texels per world px, over the MDL close-up only.
//
//   bun scripts/bake-koreans-agree-raster.mjs
//
// Writes public/koreansagree/lod-dmz.png and generated/components/koreansAgreeLevel.ts.
import { mkdirSync, writeFileSync } from "node:fs";
import { Resvg } from "@resvg/resvg-js";
import { BORDERS_D, GRATICULE_D, LAND_D } from "../generated/components/koreaStatic.ts";

const OUT_DIR = "public/koreansagree";
const OUT_TS = "generated/components/koreansAgreeLevel.ts";
const SEA = "#1B2226";
const LAND = "#3F3428";
const LAND_RIM = "#6A5838";
const INK = "#E9DDBF";

const L = { name: "dmz", kBake: 4.6, s: 6, band: [3.0, 3.6], rect: { x0: 330, y0: 430, x1: 760, y1: 1130 } };

const mix = (a, b, t) => {
  const pa = [1, 3, 5].map((i) => parseInt(a.slice(i, i + 2), 16));
  const pb = [1, 3, 5].map((i) => parseInt(b.slice(i, i + 2), 16));
  return `rgb(${pa.map((v, i) => Math.round(v + (pb[i] - v) * t)).join(",")})`;
};
const stack = (kB) => {
  const px = (v) => v / kB;
  const wlGap = 6.5 * Math.pow(kB, 0.45);
  const wlOp = [0.3, 0.2, 0.12, 0.065];
  let wl = "";
  for (let i = 3; i >= 0; i--) {
    const d = wlGap * (i + 1);
    wl += `<path d="${LAND_D}" fill="none" stroke="${mix(SEA, INK, wlOp[i])}" stroke-width="${px(2 * d + 1.15)}" stroke-linejoin="round"/>`;
    wl += `<path d="${LAND_D}" fill="none" stroke="${SEA}" stroke-width="${px(2 * d - 1.15)}" stroke-linejoin="round"/>`;
  }
  const dash = `${px(8)} ${px(5)}`;
  return `
<defs>
  <clipPath id="land"><path d="${LAND_D}" clip-rule="evenodd"/></clipPath>
</defs>
<rect x="-5000" y="-5000" width="12000" height="14000" fill="${SEA}"/>
${wl}
<path d="${GRATICULE_D}" fill="none" stroke="${INK}" stroke-opacity="0.12" stroke-width="${px(1.2)}"/>
<path d="${LAND_D}" fill="${LAND}" fill-rule="evenodd"/>
<g clip-path="url(#land)">
  <path d="${LAND_D}" fill="none" stroke="${LAND_RIM}" stroke-opacity="0.2" stroke-width="${px(28)}" stroke-linejoin="round"/>
  <path d="${LAND_D}" fill="none" stroke="${LAND_RIM}" stroke-opacity="0.28" stroke-width="${px(10)}" stroke-linejoin="round"/>
  <path d="${GRATICULE_D}" fill="none" stroke="${INK}" stroke-opacity="0.07" stroke-width="${px(1.2)}"/>
</g>
<path d="${BORDERS_D}" fill="none" stroke="${INK}" stroke-opacity="0.5" stroke-width="${px(1.7)}" stroke-dasharray="${dash}" stroke-linecap="round" stroke-linejoin="round"/>
<path d="${LAND_D}" fill="none" stroke="${INK}" stroke-opacity="0.82" stroke-width="${px(1.5)}" stroke-linejoin="round"/>`;
};

mkdirSync(OUT_DIR, { recursive: true });
const r = L.rect;
const W = Math.round((r.x1 - r.x0) * L.s);
const H = Math.round((r.y1 - r.y0) * L.s);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="${r.x0} ${r.y0} ${W / L.s} ${H / L.s}">${stack(L.kBake)}</svg>`;
const t0 = Date.now();
const png = new Resvg(svg, { fitTo: { mode: "original" }, shapeRendering: 2 }).render().asPng();
writeFileSync(`${OUT_DIR}/lod-${L.name}.png`, png);
console.log(`${OUT_DIR}/lod-${L.name}.png: ${W}x${H}, ${(png.length / 1e6).toFixed(2)} MB, ${Date.now() - t0} ms`);
const level = { name: L.name, kBake: L.kBake, s: L.s, band: L.band, x0: r.x0, y0: r.y0, w: W / L.s, h: H / L.s, W, H };
writeFileSync(
  OUT_TS,
  `// Generated by scripts/bake-koreans-agree-raster.mjs — do not edit by hand.
// One extra close level on top of the shared Korea pyramid (koreaLevels.ts), for
// KoreansAllAgree's MDL close-up: public/koreansagree/lod-dmz.png.
import type { Level } from "./koreaLevels";
export const DMZ_LEVEL: Level = ${JSON.stringify(level, null, 2)};
`,
);
console.log(`Wrote ${OUT_TS}`);
