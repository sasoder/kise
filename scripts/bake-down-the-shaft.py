class Scene:
    """Reflectance + light maps. final = alb * (ambient(y) * amb + WARM * lamp * lampf)."""

    def __init__(self, alb):
        self.alb = alb
        self.amb = np.ones((H, W), np.float32)
        self.lampf = np.zeros((H, W), np.float32)
        self.lamp = np.zeros((H, W), np.float32)
        self.emit = np.zeros((H, W, 3), np.float32)
        self.alpha = np.ones((H, W), np.float32)

    def rect(self, x0, y0, x1, y1, alb, amb=None, lampf=None, a=1.0, tone=None):
        """Axis-aligned fill; coordinates in canvas px (float edges are anti-aliased)."""
        ix0, iy0 = int(math.floor(x0)), int(math.floor(y0))
        ix1, iy1 = int(math.ceil(x1)), int(math.ceil(y1))
        ix0c, iy0c, ix1c, iy1c = max(ix0, 0), max(iy0, 0), min(ix1, W), min(iy1, H)
        if ix1c <= ix0c or iy1c <= iy0c:
            return
        xs = np.arange(ix0c, ix1c, dtype=np.float32)
        ys = np.arange(iy0c, iy1c, dtype=np.float32)
        cx = np.clip(np.minimum(xs + 1, x1) - np.maximum(xs, x0), 0, 1)
        cy = np.clip(np.minimum(ys + 1, y1) - np.maximum(ys, y0), 0, 1)
        cov = (np.outer(cy, cx) * a).astype(np.float32)
        sl = (slice(iy0c, iy1c), slice(ix0c, ix1c))
        col = np.asarray(alb, np.float32)
        if tone is not None:
            th, tw = cov.shape
            if tone.shape != (th, tw):
                tone = np.pad(tone, ((0, max(0, th - tone.shape[0])), (0, max(0, tw - tone.shape[1]))), mode="edge")[:th, :tw]
            col = col[None, None, :] * tone[..., None]
        self.alb[sl] = self.alb[sl] * (1 - cov[..., None]) + col * cov[..., None]
        if amb is not None:
            self.amb[sl] = self.amb[sl] * (1 - cov) + amb * cov
        if lampf is not None:
            self.lampf[sl] = self.lampf[sl] * (1 - cov) + lampf * cov


WOOD = []  # flattened grain strips cut from the timber photos, grain along x


def build_wood():
    """Grain strips and the wood's own hue from timber_ladder_set.jpg and timber_beam.jpg."""
    lad = load("timber_ladder_set.jpg")
    beam = load("timber_beam.jpg")
    crops = [lad[300:385, 300:560], np.rot90(lad[40:230, 290:330]), beam[10:160, 10:250]]
    for c in crops:
        L = c.mean(2)
        L = L / np.maximum(gauss_big(L, 22.0), 0.02)
        WOOD.append((1.0 + (L - L.mean()) * (0.11 / (L.std() + 1e-6))).astype(np.float32))
    # hue: the mean of the lit plank and the old beam, pulled halfway to grey (old dry timber)
    m = 0.5 * (crops[0].reshape(-1, 3).mean(0) / crops[0].mean() + crops[2].reshape(-1, 3).mean(0) / crops[2].mean())
    return (1.0 + (m - 1.0) * 0.42).astype(np.float32)


def wood_tone(hh, ww, r, along="x"):
    """Grain for a timber, cut from the timber photos: streaks along its length, a lighter top edge, a darker bottom edge."""
    src = WOOD[int(r.integers(len(WOOD)))]
    th, tw = (hh, ww) if along == "x" else (ww, hh)
    ch = int(min(src.shape[0], max(6, th * 3)))
    cw = int(min(src.shape[1], max(12, tw * 2)))
    oy = int(r.integers(0, src.shape[0] - ch + 1))
    ox = int(r.integers(0, src.shape[1] - cw + 1))
    g = resize_f(src[oy : oy + ch, ox : ox + cw], max(1, tw), max(1, th), Image.BILINEAR)
    if r.random() < 0.5:
        g = g[:, ::-1]
    g = np.clip(g, 0.6, 1.5)
    if along == "y":
        g = g.T
    g = np.ascontiguousarray(g, dtype=np.float32).copy()
    if hh >= 4 and along == "x":
        g[0, :] *= 1.22
        g[-1, :] *= 0.72
    if ww >= 4 and along == "y":
        g[:, 0] *= 1.12
        g[:, -1] *= 0.80
    return g


