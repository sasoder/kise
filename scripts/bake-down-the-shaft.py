    Yw = (np.arange(ZH, dtype=np.float32) - TOP)[:, None]  # world y per row
    rubble_tex = collage(ZH, W, rubble_src, rng, tile=260, step=190, blob=(280, 200), blob_step=(160, 130), skip=(0.0, 0.25), scale_range=(0.75, 1.15))
    broken_tex = collage(ZH, W, broken_src, rng, tile=320, step=230, blob=(360, 280), blob_step=(200, 180), skip=(0.0, 0.3), scale_range=(0.6, 0.9))
    alb = rock * ROCK_ALBEDO  # HxWx3 reflectance of the cut face
    del rock
    top = alb[:ZH]
    zone_end = smoothstep(ZH - 12.0, ZH - 130.0, np.arange(ZH, dtype=np.float32))[:, None]  # nothing of the top zone reaches its last row
    # fractured bedrock under the rubble: the bedrock, half replaced by broken limestone, fading out with depth
    t_frac = 0.55 * smoothstep(0.0, 1.0, (frac_bot[None, :] - Yw) / 160.0 + 0.30 * fbm(ZH, W, [140, 45, 14], [1.0, 0.6, 0.3], rng)) * zone_end
    top[:] = top * (1 - t_frac[..., None]) + (broken_tex * ROCK_ALBEDO) * t_frac[..., None]
    # the rubble: pale stones in a darker matrix, straight from the surface photos; its lower front follows the stones
    # the photos' bushes and their shadows would be flat dark holes: broken rock goes in their place
    # (the same rubble from somewhere else, three passes, so what fills a hole is stony too)
    for sh in ((61, 137), (-83, 211), (47, -173)):
        hole = smoothstep(0.86, 0.70, gauss(rubble_tex.mean(2), 1.5))[..., None]
        rubble_tex = rubble_tex * (1 - hole) + np.roll(rubble_tex, sh, axis=(0, 1)) * hole
    rub_l = rubble_tex.mean(2)
    t_rub = smoothstep(-0.5, 0.5, (rub_bot[None, :] - Yw) / 16.0 + 0.9 * fbm(ZH, W, [70, 22, 8], [1.0, 0.7, 0.4], rng) + np.clip(2.4 * (gauss(rub_l, 2.5) - 1.0), -1.3, 1.3)) * zone_end
    is_stone = smoothstep(0.90, 1.18, rub_l)[..., None]
    rub_col = rubble_tex * (SOIL_ALBEDO * (1 - is_stone) + RUBBLE_ALBEDO * is_stone)
    top[:] = top * (1 - t_rub[..., None]) + rub_col * t_rub[..., None]
    # the topsoil skin
    t_skin = smoothstep(-0.5, 0.5, ((lip + skin)[None, :] - Yw) / 2.5 + 0.5 * fbm(ZH, W, [14, 4], [1.0, 0.6], rng))
    skin_col = SKIN_ALBEDO[None, None, :] * (1.0 + 0.18 * vnoise(ZH, W, 3, 3, rng))[..., None]
    top[:] = top * (1 - t_skin[..., None]) + skin_col * t_skin[..., None]
    # the sky lights the face from above: ledges catch it, what is under them does not
    RELIEF_ROWS = TOP + 1900
    Lr = alb[:RELIEF_ROWS].mean(2)
    relief = np.zeros_like(Lr)
    for sg, kk in ((1.2, 1.0), (4.0, 2.0), (12.0, 4.0), (30.0, 7.0)):
        Lb = gauss(Lr, sg) if sg < 6 else gauss_big(Lr, sg)
        relief += kk * (np.roll(Lb, -1, axis=0) - np.roll(Lb, 1, axis=0)) / float(Lr.mean())
    fade_r = 1.0 - smoothstep(500.0, 1800.0, np.arange(RELIEF_ROWS, dtype=np.float32) - TOP)
    alb[:RELIEF_ROWS] *= (1.0 + np.clip(relief, -0.30, 0.30) * fade_r[:, None])[..., None]
    del Lr, relief

    sc = Scene(alb)
    spare = alb[TOP + 9320 : TOP + 9560].copy()  # untouched rock from under the sump, for the back walls of the workings
    CAPR = TOP + CAP_Y1 + 8
    rows = np.arange(H, dtype=np.float32)[:, None] - TOP
    face = np.ones((CAPR, W), np.float32)  # 1 where the cap shows the cut face (or something standing on its edge), 0 where it shows the ground
    face[:] = smoothstep(-0.9, 0.9, rows[:CAPR] - lip[None, :])

    def angular_stone(cx, cy, size, tone=1.0, base=None, top_lit=0.0, on_edge=False):
        """An angular fragment: two facets, light from above, a dark gap under it."""
        n = int(rng.integers(5, 9))
        ang = (np.arange(n) + rng.uniform(-0.35, 0.35, n)) * (2 * np.pi / n) + float(rng.uniform(0, 6.28))
        rad = size * rng.uniform(0.62, 1.0, n)
        b = float(rng.uniform(0.55, 0.9))
        rot = float(rng.uniform(-0.5, 0.5))
        pts = []
        for a_, r_ in zip(ang, rad):
            px_, py_ = r_ * math.cos(a_), r_ * b * math.sin(a_)
            pts.append((cx + px_ * math.cos(rot) - py_ * math.sin(rot), cy + px_ * math.sin(rot) + py_ * math.cos(rot)))
        R = int(size + 6)
        x0, y0 = int(cx) - R, int(cy) - R
        n_ = 2 * R + 1
        if x0 < 0 or y0 < 0 or x0 + n_ > W or y0 + n_ > ZH:
            return
        m = poly_mask(pts, x0, y0, n_, n_)
        yy_, xx_ = np.mgrid[0:n_, 0:n_].astype(np.float32)
        dy = (yy_ + y0 - cy) / (size * b)
        dx = (xx_ + x0 - cx) / size
        ca = float(rng.uniform(-0.9, 0.9))
        facet = np.where(dx * math.cos(ca) + dy * math.sin(ca) > float(rng.uniform(-0.3, 0.3)), 1.08, 0.92)
        shade = np.clip(1.06 - 0.24 * dy, 0.66, 1.3) * facet
        dst = (slice(y0, y0 + n_), slice(x0, x0 + n_))
        under = gauss(np.clip(np.roll(m, 3, axis=0) - m, 0, 1), 1.0)
        sc.alb[dst] *= (1 - 0.5 * under)[..., None]
        ty, tx = int(rng.integers(0, ZH - n_)), int(rng.integers(0, W - n_))
        tex = broken_tex[ty : ty + n_, tx : tx + n_]
        col = (ROCK_ALBEDO if base is None else base) * tone * (0.35 + 0.65 * tex) * shade[..., None]
        mm = m[..., None]
        sc.alb[dst] = sc.alb[dst] * (1 - mm) + col * mm
        if top_lit:
            sc.amb[dst] = np.maximum(sc.amb[dst], 1.0 + top_lit * m * np.clip(0.4 - dy, 0, 1))
        if on_edge and y0 + n_ <= CAPR:
            face[dst] = np.maximum(face[dst], m)

    # stones bedded in the rubble
    for _ in range(90):
        cx = float(rng.uniform(30, W - 30))
        if abs(cx - SHAFT_X) < SHAFT_HALF + 26:
            continue
        ci = int(cx)
        ya, yb = lip[ci] + skin[ci] + 8, rub_bot[ci] - 6
        size = float(np.exp(rng.uniform(math.log(5), math.log(21))))
        angular_stone(cx, TOP + float(rng.uniform(ya, yb)), size, tone=float(rng.uniform(1.0, 1.3)))
    # the face just under the edge: a little more sky than the rest, and the shade of the overhanging skin
    d_lip = rows[: TOP + 190] - lip[None, :]
    sc.amb[: TOP + 190] *= 1.0 + 0.10 * np.exp(-np.maximum(d_lip, 0) / 45.0)
    hang = 0.28 * np.exp(-np.maximum(d_lip - skin[None, :], 0) / 7.0) * smoothstep(-2.0, 2.0, d_lip - skin[None, :])
    sc.alb[: TOP + 190] *= (1 - hang * (0.6 + 0.4 * smoothstep(-1, 1, noise1d(W, 26, rng)))[None, :])[..., None]
    # stones and clods of soil that break the edge
    for bx_, bs_ in BIG_STONES:  # the big ones: half sunk in the edge
        angular_stone(float(bx_), TOP + lip[int(bx_)] - bs_ * 0.22, float(bs_), tone=float(rng.uniform(0.95, 1.15)), top_lit=0.4, on_edge=True)
    for i_ in range(60):
        cx = float(rng.uniform(30, W - 30))
        if abs(cx - SHAFT_X) < SHAFT_HALF + 40:
            continue
        clod = i_ % 3 == 2
        size = float(np.exp(rng.uniform(math.log(5), math.log(19))))
        cy = TOP + lip[int(cx)] - size * float(rng.uniform(0.0, 0.5))
        if clod:
            angular_stone(cx, cy + 3, size * 0.8, tone=float(rng.uniform(0.9, 1.25)), base=SKIN_ALBEDO, top_lit=0.5, on_edge=True)
        else:
            angular_stone(cx, cy, size, tone=float(rng.uniform(0.95, 1.2)), top_lit=0.45, on_edge=True)

    # ------------------------------------------------------------ the shaft
    print("shaft ...", flush=True)
    y_col = collar_y + TOP  # canvas row of the collar
    y_bot = DEPTH + TOP
    n_rows = y_bot + SUMP - int(y_col)
    yy = np.arange(int(y_col), y_bot + SUMP)
    wy = yy.astype(np.float32) - TOP  # world y
    # the excavation is a few px wider than the timber and not straight
    exl = XL - 2.5 - 1.8 * np.abs(noise1d(n_rows, 34, rng)) - 0.8 * noise1d(n_rows, 7, rng)
    exr = XR + 2.5 + 1.8 * np.abs(noise1d(n_rows, 34, rng)) + 0.8 * noise1d(n_rows, 7, rng)
    x0s, x1s = XL - 10, XR + 10
    cols = np.arange(x0s, x1s, dtype=np.float32)[None, :]
    inside = smoothstep(-0.8, 0.8, cols - exl[:, None]) * smoothstep(-0.8, 0.8, exr[:, None] - cols)
    # the far wall: vertical lagging boards, darker toward both walls
    board_edges = [XL + 6]
    while board_edges[-1] < XR - 6:
        board_edges.append(board_edges[-1] + float(rng.uniform(8, 13)))
    lag = np.ones((n_rows, x1s - x0s), np.float32)
    for i in range(len(board_edges) - 1):
        a, b = int(board_edges[i]) - x0s, int(board_edges[i + 1]) - x0s
        seg_tone = 0.75 + 0.5 * resize_f(rng.random((n_rows // 420 + 2, 1)).astype(np.float32), 1, n_rows, Image.NEAREST)[:, 0]
        lag[:, a:b] = seg_tone[:, None]
        lag[:, a] *= 0.45  # the gap between boards
    lag *= 1.0 + 0.12 * vnoise(n_rows, x1s - x0s, 2.0, 40, rng)
    prof = np.maximum(np.sin(np.pi * np.clip((cols - XL) / (XR - XL), 0, 1)), 0) ** 0.7  # inner shadow from both walls
    sky = np.exp(-np.maximum(wy, 0) / 95.0)[:, None]  # dusk falling in from the collar
    far_amb = (0.15 + 0.60 * sky) * (0.22 + 0.78 * prof)
    sl = (slice(int(y_col), y_bot + SUMP), slice(x0s, x1s))
    m3 = inside[..., None]
    sc.alb[sl] = sc.alb[sl] * (1 - m3) + (LAGGING_ALBEDO * lag[..., None]) * m3
    sc.amb[sl] = sc.amb[sl] * (1 - inside) + far_amb * inside
    sc.lampf[sl] = sc.lampf[sl] * (1 - inside) + 0.55 * (0.35 + 0.65 * prof) * inside
    # the rock right at the opening is a touch darker (a shadow line, not an outline)
    edge = gauss(inside, 2.2) * (1 - inside)
    sc.alb[sl] *= (1 - 0.55 * edge)[..., None]
    # the far corners: two posts in the dark, and one guide timber
    for fx, fw, fa in ((XL + 7.5, 4.2, 0.26), (XR - 11.7, 4.2, 0.26), (SHAFT_X + 11.0, 3.4, 0.22)):
        hh_ = int(y_bot - 6 - (y_col + 8))
        sc.rect(fx, y_col + 8, fx + fw, y_bot - 6, LAGGING_ALBEDO * 1.5, amb=None, tone=wood_tone(hh_, int(math.ceil(fx + fw) - math.floor(fx)), rng, "y") * fa / 0.26)

    stations_all = STATIONS + [BOTTOM_STATION]
    station_rows = [(s["y"] + TOP - s["room"] - 12, s["y"] + TOP + (SUMP if s is BOTTOM_STATION else 4)) for s in stations_all]

    def in_station(y):
        return any(a <= y <= b for a, b in station_rows)

    def bar(x0, x1, yc, th, slope, alb_, amb, lampf, tone_k):
        """A cross-piece, drawn column by column so it can sit crooked."""
        xa, xb = int(math.floor(x0)), int(math.ceil(x1))
        tone = wood_tone(int(math.ceil(th)) + 1, xb - xa, rng, "x") * tone_k
        for i_, x in enumerate(range(xa, xb)):
            yo = yc + slope * (x + 0.5 - (x0 + x1) / 2)
            cov = min(x + 1, x1) - max(x, x0)
            if cov <= 0:
                continue
            sc.rect(x, yo - th / 2, x + 1, yo + th / 2, alb_, amb=amb, lampf=lampf, a=float(cov), tone=tone[:, i_ : i_ + 1])

    # timber sets: the spacing is a man's, not a machine's
    set_rows = []
    y = y_col + 34
    while y < y_bot - 30:
        set_rows.append(y)
        y += SET_STEP * float(rng.uniform(0.85, 1.15))
    prev = y_col + 2
    for i, ys in enumerate(set_rows + [y_bot - 2]):
        # wall timbers on both sides between this set and the one above: these catch the light
        for side in (-1, 1):
            if rng.random() < 0.03:
                continue  # one is missing now and then
            pw = float(rng.uniform(4.8, 6.2))
            jog = float(rng.uniform(-0.6, 0.6))
            x0 = (XL + jog) if side < 0 else (XR - pw + jog)
            segs = [(prev + 3.0, ys - 2.0)]
            for a, b in station_rows:  # they stop at the roof of a station and start again at its floor
                nseg = []
                for s0, s1 in segs:
                    if s1 <= a or s0 >= b:
                        nseg.append((s0, s1))
                    else:
                        if s0 < a:
                            nseg.append((s0, a))
                        if s1 > b:
                            nseg.append((b, s1))
                segs = nseg
            for s0, s1 in segs:
                if s1 - s0 < 3:
                    continue
                hh, ww = int(math.ceil(s1) - math.floor(s0)), int(math.ceil(x0 + pw) - math.floor(x0))
                tone = wood_tone(hh, ww, rng, "y") * float(rng.uniform(0.85, 1.12))
                # the edge toward the open shaft is the brightest
                if side < 0:
                    tone[:, -1] *= 1.25
                else:
                    tone[:, 0] *= 1.25
                sc.rect(x0, s0, x0 + pw, s1, TIMBER_ALBEDO, amb=1.12, lampf=1.0, tone=tone)
        prev = ys
        if i >= len(set_rows) or in_station(ys):
            continue
        crooked = float(rng.uniform(-0.11, 0.11)) if rng.random() < 0.08 else float(rng.uniform(-0.012, 0.012))
        # the end plate of the set, across the far wall: deep in shadow
        if rng.random() > 0.05:
            bh = float(rng.uniform(5.6, 7.2))
            k = 0.15 + 0.40 * math.exp(-max(ys - TOP, 0) / 95.0)
            bar(XL + 6, XR - 6, ys, bh, crooked, LAGGING_ALBEDO * 1.25, k, 0.38, float(rng.uniform(0.8, 1.15)))
            sc.amb[int(ys + bh / 2) + 1 : int(ys + bh / 2) + 4, XL + 6 : XR - 6] *= 0.7
        # short bearers at both walls: nearer than the plate, still in the shaft's shadow
        for side in (-1, 1):
            if rng.random() < 0.12:
                continue
            ln = float(rng.uniform(8, 15))
            th = float(rng.uniform(5.6, 7.4))
            yo = float(rng.uniform(-1.8, 1.8))
            x0 = XL + 5 if side < 0 else XR - 5 - ln
            bar(x0, x0 + ln, ys + yo, th, crooked, TIMBER_ALBEDO, 0.50, 0.55, float(rng.uniform(0.8, 1.1)))

    # the collar: two bearers on the levelled ground
    for k, (ext, th) in enumerate([(22, 8.5), (13, 7.0)]):
        ya = y_col - 7.5 + k * 8.2
        hh, ww = int(math.ceil(ya + th) - math.floor(ya)), int(XR + ext - (XL - ext))
        tone = wood_tone(hh, ww, rng, "x") * (1.08 - 0.12 * k)
        sc.rect(XL - ext, ya, XR + ext, ya + th, TIMBER_ALBEDO * np.array([0.95, 0.98, 1.0], np.float32), amb=1.25, lampf=0.0, tone=tone)
        if k == 0:
            r0, r1 = int(math.floor(ya)), int(math.ceil(ya + th))
            cov = np.zeros((r1 - r0, W), np.float32)
            cov[:, XL - ext : XR + ext] = 1.0
            cov[0, :] *= 1 - (ya - r0)
            face[r0:r1] = np.maximum(face[r0:r1], cov)

    # ------------------------------------------------------------ stations and drifts
    print("stations ...", flush=True)
    lamps = []

    def station(st):
        """A level station: a low room across the shaft and a hand-cut drift each way that pinches out."""
        yf = st["y"] + TOP
        h, room = st["h"], st["room"]
        r_ = np.random.default_rng(int(st["y"]) * 13 + 5)
        cols_ = np.arange(max(0, XL - st["left"] - 16), min(W, XR + st["right"] + 16))
        n = len(cols_)
        xf = cols_.astype(np.float32)
        dl = np.maximum(0.0, np.maximum(XL - xf, xf - XR))  # px beyond the shaft wall
        length = np.where(xf < SHAFT_X, float(st["left"]), float(st["right"])).astype(np.float32)
        near = 1.0 - smoothstep(35.0, 150.0, dl)
        hh = h + (room - h) * near  # a low room at the shaft, then a tunnel of one height
        close = smoothstep(length - 34.0, length + 2.0, dl) ** 1.6  # only the heading itself is rounded
        rough = smoothstep(18.0, 110.0, dl)  # near the shaft the floor is level
        roof = yf - hh * (1 - 0.40 * close) + 3.0 * noise1d(n, 44, r_) + 1.6 * noise1d(n, 12, r_)
        floor = yf - hh * 0.10 * close + rough * (2.0 * noise1d(n, 60, r_) + 1.0 * noise1d(n, 8, r_))
        r0, r1 = int(yf - room - 30), int(yf + 12)
        nr = r1 - r0
        rr = np.arange(r0, r1, dtype=np.float32)[:, None]
        m = smoothstep(-0.8, 0.8, rr - roof[None, :]) * smoothstep(-0.8, 0.8, floor[None, :] - rr)
        jag = 2.5 * noise1d(nr, 9, r_) + 4.0 * noise1d(nr, 30, r_)
        m *= smoothstep(1.0, -1.0, dl[None, :] - (length[None, :] + jag[:, None]))
        sl_ = (slice(r0, r1), slice(int(cols_[0]), int(cols_[-1]) + 1))
        v = np.clip((rr - roof[None, :]) / np.maximum(floor - roof, 1)[None, :], 0, 1)
        z_roof = smoothstep(0.26, 0.05, v)  # the roof, seen from below
        z_floor = smoothstep(0.76, 0.95, v)  # the floor, running back to the wall
        ao = 0.5 + 0.5 * np.maximum(np.sin(np.pi * v), 0) ** 0.5
        so = int(r_.integers(0, spare.shape[0] - nr))
        sx = int(r_.integers(0, W - n + 1))
        back = spare[so : so + nr, sx : sx + n].copy()
        if r_.random() < 0.5:
            back = back[:, ::-1]
        back = 1.0 + (back / np.maximum(back.mean(), 1e-3) - 1.0) * 1.5  # the back wall is rough: it shows in a raking light
        back = np.clip(back, 0.25, 2.2) * ROCK_ALBEDO.mean() * np.array([1.0, 0.98, 0.95], np.float32)
        muck = 1.0 + z_floor * (0.25 + 0.4 * vnoise(nr, n, 4, 2.5, r_))
        back = back * ((1.0 - 0.40 * z_roof) * muck)[..., None]
        edge_ = gauss(m, 2.4) * (1 - m)
        sc.alb[sl_] *= (1 - 0.6 * edge_)[..., None]
        m3_ = m[..., None]
        sc.alb[sl_] = sc.alb[sl_] * (1 - m3_) + back * m3_
        far = (1.0 - 0.6 * smoothstep(0.15, 1.0, dl / length))[None, :]  # our own lamp reaches into the opened tunnel less and less
        sc.amb[sl_] = sc.amb[sl_] * (1 - m) + 0.21 * far * ao * m
        sc.lampf[sl_] = np.maximum(sc.lampf[sl_] * (1 - m), ao * m)
        prox = gauss(m, 11.0) * (1 - m)  # a little of the light on the cut rock around the opening
        sc.lampf[sl_] = np.maximum(sc.lampf[sl_], 0.5 * prox)

        def col_at(x):
            return int(np.clip(round(x) - int(cols_[0]), 0, n - 1))

        # timber sets along the drift: a post against the back wall and the end of its cap
        lx = (XR + st["lamp_dx"]) if st["lamp"] > 0 else (XL - st["lamp_dx"])
        for side, ln in ((-1, st["left"]), (1, st["right"])):
            x = 40.0 + float(r_.uniform(0, 14))
            while x < ln - 30:
                cxp = (XL - x) if side < 0 else (XR + x)
                if abs(cxp - lx) < 26:  # the lamp hangs between two sets, not on a post
                    x += 30.0
                    continue
                ci = col_at(cxp)
                pw = float(r_.uniform(4.2, 5.6))
                ytop, ybot = roof[ci] + 6.5, floor[ci] - 0.5
                hh_, ww_ = int(math.ceil(ybot) - math.floor(ytop)), int(math.ceil(cxp + pw / 2) - math.floor(cxp - pw / 2))
                if hh_ > 12:
                    sc.rect(cxp - pw / 2, ytop, cxp + pw / 2, ybot, TIMBER_ALBEDO, amb=0.30, lampf=0.9, tone=wood_tone(hh_, ww_, r_, "y") * float(r_.uniform(0.8, 1.05)))
                    cw, ch = float(r_.uniform(8, 10.5)), float(r_.uniform(6, 7.5))
                    sc.rect(cxp - cw / 2, ytop - ch, cxp + cw / 2, ytop, TIMBER_ALBEDO, amb=0.32, lampf=0.9, tone=wood_tone(int(math.ceil(ytop) - math.floor(ytop - ch)), int(math.ceil(cxp + cw / 2) - math.floor(cxp - cw / 2)), r_, "x"))
                x += float(r_.uniform(58, 78))
        # the shaft's own timbers at the station: a cap under the roof and a sill at the floor
        capy = roof[col_at(SHAFT_X)] + 3.0
        sc.rect(XL - 12, capy, XR + 12, capy + 7.2, TIMBER_ALBEDO, amb=0.5, lampf=1.0, tone=wood_tone(8, XR - XL + 24, r_, "x"))
        sc.rect(XL - 16, yf - 4.2, XR + 16, yf + 1.0, TIMBER_ALBEDO * 0.92, amb=0.5, lampf=1.0, tone=wood_tone(6, XR - XL + 32, r_, "x"))
        lamps.append(dict(x=float(lx), y=float(roof[col_at(lx)] + 15.0), r=st["lamp_r"], k=st["lamp_k"]))
        return roof, floor, cols_

    for s in STATIONS:
        station(s)
    b = BOTTOM_STATION
    yf = b["y"] + TOP
    roof_b, floor_b, cols_b = station(b)
    # two posts frame the shaft where it comes into the bottom station
    for side in (-1, 1):
        px_ = XL - 7.5 if side < 0 else XR + 1.5
        ytop = roof_b[int(px_ - cols_b[0])] + 2
        hh_ = int(math.ceil(yf - 1) - math.floor(ytop))
        sc.rect(px_, ytop, px_ + 6.2, yf - 1, TIMBER_ALBEDO, amb=0.5, lampf=1.0, tone=wood_tone(hh_, 7, rng, "y"))
    # the sump: black water a little under the floor
    sump_sl = (slice(yf + 1, yf + SUMP), slice(XL - 3, XR + 3))
    sy = np.arange(SUMP - 1, dtype=np.float32)[:, None]
    sc.amb[sump_sl] *= 0.75 - 0.5 * smoothstep(0, SUMP, sy)
    sc.lampf[sump_sl] *= 0.5 * smoothstep(26, 0, sy)
    wl = yf + 30
    sc.alb[wl : yf + SUMP, XL - 2 : XR + 2] *= 0.35
    sc.amb[wl : yf + SUMP, XL - 2 : XR + 2] *= 0.5
    sc.rect(XL - 1, wl, XR + 1, wl + 1.3, np.array([0.5, 0.42, 0.33], np.float32), amb=0.25, lampf=0.9, a=0.55)
    bot = yf + SUMP
    sc.alb[bot - 6 : bot + 2, XL - 6 : XR + 6] = sc.alb[bot + 20 : bot + 28, XL - 6 : XR + 6]
    sc.amb[bot - 6 : bot + 2, XL - 6 : XR + 6] = np.linspace(0.3, 1.0, 8, dtype=np.float32)[:, None]
    sc.lampf[bot - 6 : bot + 2, XL - 6 : XR + 6] = 0.0
    # the hoist cable
    cab = SHAFT_X - 5.2
    cab_end = TOP + CABLE_LIVE_Y
    hh = cab_end - int(y_col - 8)
    tone = np.repeat(1.0 + 0.10 * vnoise(hh, 2, 1.5, 30, rng)[:, :1], 3, axis=1)
    sc.rect(cab, y_col - 8, cab + 1.7, cab_end, STEEL, amb=1.2, lampf=1.0, a=0.85, tone=tone)
    face[int(y_col - 8) : int(y_col), int(cab) : int(cab) + 2] = np.maximum(face[int(y_col - 8) : int(y_col), int(cab) : int(cab) + 2], 0.85)
    # the bucket on the end of the cable
    bx, by = cab + 0.85, yf - 22
    for i in range(18):
        t = i / 17.0
        half = 7.2 + 2.6 * (1 - t)  # wider at the rim
        sc.rect(bx - half, by - 18 + i, bx + half, by - 17 + i, STEEL * (0.62 + 0.25 * (1 - t)), amb=0.5, lampf=1.0)
    sc.rect(bx - 10.2, by - 19.2, bx + 10.2, by - 17.6, STEEL * 1.15, amb=0.5, lampf=1.0)
    for i in range(26):  # the bail
        t = i / 25.0
        for sgn in (-1, 1):
            xx_ = bx + sgn * 9.2 * t
            sc.rect(xx_ - 0.7, by - 44 + 26 * t, xx_ + 0.7, by - 43 + 26 * t, STEEL * 0.9, amb=0.5, lampf=1.0, a=0.85)

    # ------------------------------------------------------------ lamps
    for lp in lamps:
        R = int(lp["r"] * 8)
        ya, yb = max(0, int(lp["y"]) - R), min(H, int(lp["y"]) + R)
        xa, xb = max(0, int(lp["x"]) - R), min(W, int(lp["x"]) + R)
        yy_, xx_ = np.mgrid[ya:yb, xa:xb].astype(np.float32)
        d2 = (xx_ - lp["x"]) ** 2 + ((yy_ - lp["y"]) * 1.15) ** 2
        fall = lp["k"] / (1.0 + d2 / (lp["r"] ** 2))  # inverse square with a soft core
        fall *= smoothstep(R, R * 0.55, np.sqrt(d2))
        sc.lamp[ya:yb, xa:xb] = np.maximum(sc.lamp[ya:yb, xa:xb], fall)
        core = np.exp(-d2 / (2 * 2.1**2))
        haze = 0.20 * np.exp(-np.sqrt(d2) / 16.0)
        sc.emit[ya:yb, xa:xb] += (core[..., None] * np.array([1.0, 0.86, 0.60], np.float32) + haze[..., None] * np.array([0.85, 0.50, 0.20], np.float32)) * lp["k"]

    # ------------------------------------------------------------ a person for scale, in the lit drift of the 900 ft station
    fm = figure_mask(FIGURE_H)
    fh, fw = fm.shape
    fx0, fy0 = int(FIGURE_X - fw / 2), int(yf - 1 - fh)
    fsl = (slice(fy0, fy0 + fh), slice(fx0, fx0 + fw))
    # the shadow it throws away from the lamp: along the floor and, fainter, up the back wall
    ya, yb, xa, xb = fy0 - 6, yf + 4, fx0 - 4, fx0 + fw + 70
    yy_, xx_ = np.mgrid[ya:yb, xa:xb].astype(np.float32)
    on_floor = np.exp(-(((xx_ - (FIGURE_X + 24)) / 30.0) ** 2 + ((yy_ - (yf - 4)) / 5.0) ** 2))
    on_wall = np.exp(-(((xx_ - (FIGURE_X + 22)) / 20.0) ** 2 + ((yy_ - (yf - 32)) / 30.0) ** 2))
    sc.lampf[ya:yb, xa:xb] *= 1.0 - np.clip(0.62 * on_floor + 0.30 * on_wall, 0, 0.8)
    rim = fm * np.clip(1.0 - np.roll(fm, 2, axis=1), 0, 1)  # the side toward the lamp
    rim[:, :2] = fm[:, :2]
    f3 = fm[..., None]
    sc.alb[fsl] = sc.alb[fsl] * (1 - f3) + np.array([0.040, 0.038, 0.040], np.float32) * f3
    sc.amb[fsl] = sc.amb[fsl] * (1 - fm) + 0.20 * fm
    sc.lampf[fsl] = sc.lampf[fsl] * (1 - fm) + 0.05 * fm
    sc.emit[fsl] *= (1 - f3)
    r3 = (0.85 * rim)[..., None]
    sc.alb[fsl] = sc.alb[fsl] * (1 - r3) + np.array([0.44, 0.40, 0.35], np.float32) * r3
    sc.lampf[fsl] = np.maximum(sc.lampf[fsl], 0.9 * rim)

    # ------------------------------------------------------------ light it
    print("lighting ...", flush=True)
    gl = (slice(yf - 160, yf + 70), slice(110, 1130))
    glow_map = gauss(sc.alb[gl] * WARM[None, None, :] * (sc.lamp[gl] * sc.lampf[gl])[..., None], 1.15)
    Image.fromarray(np.clip(glow_map * 255.0 + 0.5, 0, 255).astype(np.uint8)).save(os.path.join(SRC, "station_light.png"), optimize=True)
    print("station_light.png: plate x 110, world y", yf - 160 - TOP, "size", glow_map.shape[1], "x", glow_map.shape[0], flush=True)
    wyr = np.arange(H, dtype=np.float32) - TOP
    dusk_w = 1.0 - smoothstep(0.0, 1500.0, wyr)  # the sky's light dies over the first 150 ft
    lamp_w = smoothstep(150.0, 1500.0, wyr)  # and our own lamp takes over
    hue_w = smoothstep(300.0, 3000.0, wyr)  # its colour goes from the dusk's blue-grey to warm grey over ~300 ft
    lamp_col = (DUSK * (float(LAMP.mean()) / float(DUSK.mean())))[None, :] * (1 - hue_w)[:, None] + LAMP[None, :] * hue_w[:, None]
    ambient = DUSK[None, :] * dusk_w[:, None] + lamp_col * lamp_w[:, None]
    out = np.empty((H, W, 3), np.float32)
    CH = 2048
    for y0 in range(0, H, CH):
        y1 = min(H, y0 + CH)
        light = ambient[y0:y1, None, :] * sc.amb[y0:y1, :, None] + WARM[None, None, :] * (sc.lamp[y0:y1] * sc.lampf[y0:y1])[..., None]
        o = sc.alb[y0:y1] * light + sc.emit[y0:y1]
        o = np.maximum(o, 0)
        hi = np.maximum(o - 0.6, 0)  # a soft shoulder instead of a clip
        o = np.minimum(o, 0.6) + 0.4 * (1.0 - np.exp(-hi / 0.4))
        out[y0:y1] = BLACK + (1.0 - BLACK) * o
    del sc.alb, sc.amb, sc.lampf, sc.lamp, sc.emit

    # ------------------------------------------------------------ the footage is soft: so is this
    print("soften + save ...", flush=True)
    soft = np.empty_like(out)
    for y0 in range(0, H, CH):
        y1 = min(H, y0 + CH)
        a0, a1 = max(0, y0 - 8), min(H, y1 + 8)
        soft[y0:y1] = gauss(out[a0:a1], 1.15)[y0 - a0 : y0 - a0 + (y1 - y0)]
    del out

    # ------------------------------------------------------------ the cap: the footage's own ground, the edge, the brush
    capn = TOP + CAP_Y1
    ref = load("ref_frame0.png")
    ground = collage(capn, W, gravel_src, rng, tile=170, step=115, blob=(200, 150), blob_step=(120, 100), skip=(0.0, 0.3), scale_range=(1.0, 1.3))
    ground = ground / np.maximum(gauss_big(ground.mean(2), 22.0), 0.2)[..., None]  # even gravel: the patches' own blotches are gone
    ground = ground * GRAVEL * (1.0 + 0.03 * vnoise(capn, W, 110, 36, rng))[..., None]
    yw = (np.arange(capn, dtype=np.float32) - TOP)[:, None]
    # a few pale stones lying on it, each with its shadow
    for _ in range(46):
        cx, sz = float(rng.uniform(6, W - 6)), float(np.exp(rng.uniform(math.log(1.6), math.log(5.5))))
        cy = TOP + lip[int(cx)] - float(rng.uniform(4, 70))
        R = int(sz + 5)
        x0, y0 = int(cx) - R, int(cy) - R
        if x0 < 0 or y0 < 0 or x0 + 2 * R + 1 > W or y0 + 2 * R + 1 > capn:
            continue
        yy_, xx_ = np.mgrid[y0 : y0 + 2 * R + 1, x0 : x0 + 2 * R + 1].astype(np.float32)
        m = smoothstep(1.25, 0.75, np.sqrt(((xx_ - cx) / sz) ** 2 + ((yy_ - cy) / (sz * 0.62)) ** 2))
        sh = 0.30 * smoothstep(1.5, 0.6, np.sqrt(((xx_ - cx - 0.3 * sz) / (sz * 1.15)) ** 2 + ((yy_ - cy - 0.55 * sz) / (sz * 0.6)) ** 2))
        dst = (slice(y0, y0 + 2 * R + 1), slice(x0, x0 + 2 * R + 1))
        g_ = ground[dst] * (1 - sh * (1 - m))[..., None]
        ground[dst] = g_ * (1 - m[..., None]) + (GRAVEL * float(rng.uniform(1.18, 1.5)) * np.array([1.06, 1.0, 0.95], np.float32)) * m[..., None]
    ground = gauss(ground, 0.7)
    # the ground toward the edge: the rim catches a little more sky
    ground *= (1.0 + 0.10 * np.exp(-np.maximum(lip[None, :] - yw, 0) / 7.0))[..., None]
    # its far edge: uneven, and soft over a dozen px only (a rise in the ground, not a fog)
    y_top = -(GROUND + OVERLAP) - 12.0 + np.clip(22.0 + 16.0 * noise1d(W, 190, rng) + 8.0 * noise1d(W, 55, rng) + 3.0 * noise1d(W, 14, rng), 0.0, 52.0)
    a_top = smoothstep(0.0, 1.0, (yw - y_top[None, :]) / 13.0 + 0.30 * fbm(capn, W, [30, 9, 3], [1.0, 0.6, 0.35], rng))
    a_top[yw[:, 0] < -(GROUND + OVERLAP) - 17.0] = 0.0
    fmask = gauss(face[:capn], 0.6)[..., None]
    cap_rgb = ground * (1 - fmask) + soft[:capn] * fmask
    cap_a = np.maximum(fmask[..., 0], a_top)
    # dry brush on the edge: it stands BEHIND the edge's stones
    for px_, tw_, th_, lean, spread, dens, box, tone_ in TUFTS:
        tip, body = brush_colours(ref, box)
        rgb, m = draw_tuft(tw_, th_, tip, body, rng, lean, spread, dens)
        x0 = int(px_ - tw_ / 2)
        y0 = int(TOP + lip[int(px_)] + 4 - th_)
        if x0 < 0 or y0 < 0 or x0 + tw_ > W or y0 + th_ > capn:
            continue
        dst = (slice(y0, y0 + th_), slice(x0, x0 + tw_))
        behind = 1 - fmask[dst][..., 0]
        m = m * behind
        yy_, xx_ = np.mgrid[0:th_, 0:tw_].astype(np.float32)
        foot = 0.32 * np.exp(-(((xx_ - tw_ / 2) / (tw_ * 0.32)) ** 2 + ((yy_ - (th_ - 4)) / 5.0) ** 2)) * behind  # it shades the ground at its foot
        cap_rgb[dst] *= (1 - foot * (1 - m))[..., None]
        cap_rgb[dst] = cap_rgb[dst] * (1 - m[..., None]) + rgb * tone_ * m[..., None]
        cap_a[dst] = np.maximum(cap_a[dst], m)

    u8 = np.clip(soft * 255.0 + 0.5, 0, 255).astype(np.uint8)
    plate = Image.fromarray(u8[TOP + PLATE_Y0 :])
    plate.save(os.path.join(SRC, "underground_plate.jpg"), quality=90, subsampling=1, optimize=True)
    fade = np.clip((capn - np.arange(capn, dtype=np.float32)) / 24.0, 0, 1)
    cap_a = np.clip(cap_a, 0, 1) * fade[:, None]
    cap = np.dstack([np.clip(cap_rgb * 255.0 + 0.5, 0, 255).astype(np.uint8), np.clip(cap_a * 255 + 0.5, 0, 255).astype(np.uint8)])
    Image.fromarray(cap).save(os.path.join(SRC, "underground_cap.png"), optimize=True)

    # grain for the live layer: grey, soft like compressed video grain
    g = np.random.default_rng(7).standard_normal((2048, 1216)).astype(np.float32)
    g = gauss(g, 1.0)
    g = g / g.std()
    Image.fromarray(np.clip(128 + g * 30, 0, 255).astype(np.uint8)).save(os.path.join(SRC, "grain_tile.png"), optimize=True)

    top_row = int(np.where((cap_a > 1.5 / 255).any(axis=1))[0].min())
    print("cap: topmost visible row is world y", top_row - TOP, "-> the component's SLIDE must be at least", -(top_row - TOP) - GROUND, flush=True)
    cpx = u8[TOP + CABLE_LIVE_Y - 300 : TOP + CABLE_LIVE_Y - 20, int(cab + 0.85)].reshape(-1, 3).mean(0)
    print("cable: plate x", round(cab + 0.85, 2), "live from world y", CABLE_LIVE_Y, "to", DEPTH - 64, "colour", np.round(cpx, 1), "| collar y", round(collar_y, 1), flush=True)
    print("plate", plate.size, "cap", (W, capn), "lamps", [(round(l["x"]), round(l["y"] - TOP)) for l in lamps], flush=True)

    if crops_dir:
        show = u8.copy()
        # the cap over the clip's ground colour, as the component lays it
        bg = np.array([87, 104, 112], np.float32)
        a_ = cap_a[..., None]
        show[:capn] = (cap_rgb * 255.0 * a_ + show[:capn] * 0 + bg * (1 - a_)).clip(0, 255).astype(np.uint8)
        show[capn - 24 : capn] = (cap_rgb[capn - 24 : capn] * 255.0 * fade[capn - 24 :, None, None] + u8[capn - 24 : capn] * (1 - fade[capn - 24 :, None, None])).clip(0, 255).astype(np.uint8)
        full = Image.fromarray(show)

        def crop(name, world_y_centre, x0=80):
            y0 = int(world_y_centre + TOP - 960)
            y0 = max(0, min(H - 1920, y0))
            full.crop((x0, y0, x0 + 1080, y0 + 1920)).save(os.path.join(crops_dir, name), quality=92)

        # the three review crops: depth 0, ~450 ft and 900 ft
        full.crop((140, 0, 1220, 1920)).save(os.path.join(crops_dir, "plate_top.jpg"), quality=92)
        crop("plate_mid.jpg", 4500)
        crop("plate_bottom.jpg", 9000)
        crop("plate_200.jpg", 2000)
        full.resize((W // 5, H // 5), Image.LANCZOS).save(os.path.join(crops_dir, "plate_overview.jpg"), quality=88)


