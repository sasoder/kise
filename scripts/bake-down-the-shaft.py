# ---------------------------------------------------------------- helpers
def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def resize_f(a, w, h, resample=Image.BICUBIC):
    return np.asarray(Image.fromarray(np.ascontiguousarray(a, dtype=np.float32)).resize((int(w), int(h)), resample))


def gauss(a, sigma):
    """Separable Gaussian, reflect edges. a: HxW or HxWxC float32."""
    if sigma <= 0:
        return a
    r = max(1, int(math.ceil(3 * sigma)))
    k = np.exp(-0.5 * (np.arange(-r, r + 1) / sigma) ** 2).astype(np.float32)
    k /= k.sum()
    for axis in (0, 1):
        pad = [(0, 0)] * a.ndim
        pad[axis] = (r, r)
        ap = np.pad(a, pad, mode="reflect")
        out = np.zeros_like(a, dtype=np.float32)
        n = a.shape[axis]
        for i, kv in enumerate(k):
            sl = [slice(None)] * a.ndim
            sl[axis] = slice(i, i + n)
            out += kv * ap[tuple(sl)]
        a = out
    return a


def gauss_big(a, sigma):
    """Large-sigma Gaussian through a reduced copy (2-D only)."""
    ds = max(1, int(sigma / 3))
    if ds == 1:
        return gauss(a, sigma)
    h, w = a.shape
    small = resize_f(a, max(2, w // ds), max(2, h // ds), Image.BOX)
    small = gauss(small, sigma / ds)
    return resize_f(small, w, h, Image.BICUBIC)


def vnoise(h, w, sx, sy, r):
    """Smooth value noise, about unit variance, feature size sx x sy px."""
    gh = int(math.ceil(h / sy)) + 4
    gw = int(math.ceil(w / sx)) + 4
    g = r.standard_normal((gh, gw)).astype(np.float32)
    big = resize_f(g, max(w + 2, int(gw * sx)), max(h + 2, int(gh * sy)))
    oy = int(r.integers(0, max(1, big.shape[0] - h)))
    ox = int(r.integers(0, max(1, big.shape[1] - w)))
    out = big[oy : oy + h, ox : ox + w]
    return out / (out.std() + 1e-6)


def fbm(h, w, scales, weights, r):
    out = np.zeros((h, w), np.float32)
    for s, wt in zip(scales, weights):
        out += wt * vnoise(h, w, s, s, r)
    return out / math.sqrt(sum(x * x for x in weights))


def noise1d(n, scale, r):
    g = r.standard_normal(int(math.ceil(n / scale)) + 4).astype(np.float32)
    big = resize_f(g[None, :], max(n + 2, int(len(g) * scale)), 1)[0]
    o = int(r.integers(0, max(1, len(big) - n)))
    out = big[o : o + n]
    return out / (out.std() + 1e-6)


_GRID = rng.standard_normal((257, 263)).astype(np.float32)


def rnoise(h, w, s_across, s_along, phi_deg, r, ds=4, y0=0):
    """Anisotropic noise elongated along a direction phi degrees off vertical."""
    phi = math.radians(phi_deg)
    hh, ww = int(math.ceil(h / ds)) + 1, int(math.ceil(w / ds)) + 1
    Y, X = np.mgrid[0:hh, 0:ww].astype(np.float32) * ds
    Y += y0
    u = (X * math.cos(phi) - Y * math.sin(phi)) / s_across + float(r.uniform(0, 200))
    v = (X * math.sin(phi) + Y * math.cos(phi)) / s_along + float(r.uniform(0, 200))
    u0 = np.floor(u).astype(np.int64)
    v0 = np.floor(v).astype(np.int64)
    fu = u - u0
    fv = v - v0
    fu = fu * fu * (3 - 2 * fu)
    fv = fv * fv * (3 - 2 * fv)
    gh, gw = _GRID.shape
    a = _GRID[v0 % gh, u0 % gw]
    b = _GRID[v0 % gh, (u0 + 1) % gw]
    c = _GRID[(v0 + 1) % gh, u0 % gw]
    d = _GRID[(v0 + 1) % gh, (u0 + 1) % gw]
    n = (a * (1 - fu) + b * fu) * (1 - fv) + (c * (1 - fu) + d * fu) * fv
    n = resize_f(n, ww * ds, hh * ds)[:h, :w]
    return n / 0.52  # value noise with smoothstep weights has std ~0.52


def load(name):
    return np.asarray(Image.open(os.path.join(SRC, name)).convert("RGB")).astype(np.float32) / 255.0


def flatten(img, sigma=70.0, std_target=0.17, chroma_keep=0.45):
    """Remove the photo's own lighting; return reflectance-like values, mean 1."""
    lum = img.mean(2)
    low = gauss_big(lum, sigma)
    rel = img / np.maximum(low, 0.03)[..., None]
    rel = rel / rel.reshape(-1, 3).mean(0)
    L = np.maximum(rel.mean(2, keepdims=True), 0.12)
    c = rel / L - 1.0
    rel = L * (1.0 + 0.045 * np.tanh(c * chroma_keep / 0.045))  # stains stay, no coloured blotches
    L = np.maximum(rel.mean(2, keepdims=True), 0.12)
    d = (L - L.mean()) * (std_target / (L.std() + 1e-6))
    d = 0.45 * np.tanh(d / 0.45)  # no black holes, no blown facets
    return np.clip(rel / L * (1.0 + d), 0.05, 2.3).astype(np.float32)


U8 = 110.0  # 8-bit value of reflectance 1.0 in the flattened sources


def to_u8(rel):
    return Image.fromarray(np.clip(rel * U8, 0, 255).astype(np.uint8))


def sharpness(rel):
    """Local amount of fine detail (so soft, out-of-focus parts of a photo can be avoided)."""
    L = rel.mean(2)
    return gauss_big(np.abs(L - gauss(L, 2.0)), 45.0)


