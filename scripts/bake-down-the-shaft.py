_RECENT = {}  # per source photo: the crops used last, so the same piece of rock is not laid twice close together


def patch(sources, S, r, scale_range=(0.9, 1.3), max_rot=9.0, tries=6):
    """One reflectance patch (up to SxS) from a random source, crop, flip, rotation, scale.
    The patch is never enlarged beyond scale_range, so it can come back smaller than S."""
    wts = np.array([s[2] for s in sources], np.float64)
    im, rects, _, sharp = sources[int(r.choice(len(sources), p=wts / wts.sum()))]
    x0, y0, x1, y1 = rects[int(r.integers(len(rects)))]
    scale = float(r.uniform(*scale_range))
    need = int(S / scale * 1.17) + 2
    side = min(x1 - x0, y1 - y0)
    lim = int(0.66 * side) if sharp is not None else side  # rock photos: a crop is never most of the photo
    if need > lim:
        need = lim
        S = min(S, int(lim / 1.17 * (scale if sharp is not None else scale_range[1])))
    rec = _RECENT.setdefault(id(im), [])
    best = None
    for _ in range(tries if sharp is not None else 1):
        cx = int(r.integers(x0, x1 - need + 1))
        cy = int(r.integers(y0, y1 - need + 1))
        sc_ = 0.0 if sharp is None else float(sharp[cy + need // 4 : cy + need - need // 4 : 24, cx + need // 4 : cx + need - need // 4 : 24].mean())
        fresh = not any(abs(cx - qx) < need * 0.5 and abs(cy - qy) < need * 0.5 for qx, qy in rec[-5:])
        if best is None or (fresh, sc_) > best[0]:
            best = ((fresh, sc_), cx, cy)
    _, cx, cy = best
    if sharp is not None:
        rec.append((cx, cy))
    crop = im.crop((cx, cy, cx + need, cy + need))
    if r.random() < 0.5:
        crop = ImageOps.mirror(crop)
    if r.random() < 0.35:
        crop = ImageOps.flip(crop)
    crop = crop.rotate(float(r.uniform(-max_rot, max_rot)), Image.BICUBIC)
    inner = int(need / 1.17)
    o = (need - inner) // 2
    crop = crop.crop((o, o, o + inner, o + inner)).resize((S, S), Image.LANCZOS)
    p = np.asarray(crop).astype(np.float32) / U8
    return p / np.maximum(p.reshape(-1, 3).mean(0), 1e-3)  # no tint and no tone step from patch to patch


def blob_mask(S, r, ax=0.78, ay=0.90, feather=0.11):
    """Irregular blob alpha in an SxS square, zero at the square's edge."""
    lin = np.linspace(-1, 1, S, dtype=np.float32)
    X, Y = np.meshgrid(lin, lin)
    d = np.sqrt((X / ax) ** 2 + (Y / ay) ** 2)
    n = fbm(S, S, [S / 3.0, S / 7.0, S / 18.0, S / 45.0], [1.0, 0.6, 0.35, 0.2], r)
    # the noise shapes the edge, but toward the square's own edge the blob is pushed under the threshold for good:
    # a patch is never cut along a straight line
    m = 1.0 - d + 0.26 * n - 1.3 * smoothstep(0.62, 1.0, np.maximum(np.abs(X), np.abs(Y)))
    a = smoothstep(0.14, 0.14 + feather, m)
    return a.astype(np.float32)


def collage(h, w, sources, r, tile=640, step=480, blob=(960, 620), blob_step=(540, 430), skip=(0.0, 0.35), scale_range=(0.9, 1.3)):
    """Texture without a grid: cross-faded base tiles, then layers of irregular blobs."""
    acc = np.zeros((h, w, 3), np.float32)
    wsum = np.zeros((h, w), np.float32)
    for ty in range(-tile // 3, h, step):
        for tx in range(-tile // 3, w, step):
            p = patch(sources, tile, r, scale_range)
            S = p.shape[0]
            # smaller patches are laid several times so the base has no holes
            sub = max(S // 2, S - 140)
            ramp = np.minimum(np.arange(S), np.arange(S)[::-1]).astype(np.float32) + 1.0
            ramp = np.minimum(ramp / float((tile - step) if S >= tile else (S - sub)), 1.0)  # cross-fade over the whole overlap: no hard patch edge anywhere
            wt = np.outer(ramp, ramp)
            for oy in range(0, tile - S + sub, sub) if S < tile else [0]:
                for ox in range(0, tile - S + sub, sub) if S < tile else [0]:
                    py, px = ty + oy, tx + ox
                    ys, xs = max(py, 0), max(px, 0)
                    ye, xe = min(py + S, h), min(px + S, w)
                    if ye <= ys or xe <= xs:
                        continue
                    sl = (slice(ys - py, ye - py), slice(xs - px, xe - px))
                    q = p
                    if oy or ox:  # never the same patch twice side by side
                        q = patch(sources, S, r, scale_range)
                        if q.shape[0] != S:
                            q = p[::-1, ::-1]
                    acc[ys:ye, xs:xe] += q[sl] * wt[sl][..., None]
                    wsum[ys:ye, xs:xe] += wt[sl]
    out = acc / np.maximum(wsum, 1e-4)[..., None]
    out[wsum < 1e-4] = 1.0
    del acc, wsum
    for layer, (bsize, bstep, bskip) in enumerate(zip(blob, blob_step, skip)):
        off = (layer * bstep) // 2
        centres = [(cy, cx) for cy in range(-off, h + bstep, bstep) for cx in range(-off, w + bstep, bstep)]
        order = r.permutation(len(centres))
        for i in order:
            if r.random() < bskip:
                continue
            cy, cx = centres[i]
            cy += int(r.integers(-bstep // 3, bstep // 3 + 1))
            cx += int(r.integers(-bstep // 3, bstep // 3 + 1))
            p = patch(sources, int(bsize * r.uniform(0.85, 1.15)), r, scale_range)
            S = p.shape[0]
            ty, tx = cy - S // 2, cx - S // 2
            ys, xs = max(ty, 0), max(tx, 0)
            ye, xe = min(ty + S, h), min(tx + S, w)
            if ye <= ys or xe <= xs:
                continue
            a = blob_mask(S, r)
            sl = (slice(ys - ty, ye - ty), slice(xs - tx, xe - tx))
            aa = a[sl][..., None]
            out[ys:ye, xs:xe] = out[ys:ye, xs:xe] * (1 - aa) + p[sl] * aa
    return out


# ---------------------------------------------------------------- bedrock structure
PHI = 13.0  # the beds dip steeply: 13 degrees off vertical


def sample_profile(prof, pos):
    pos = np.clip(pos, 0, len(prof) - 2)
    i0 = np.floor(pos).astype(np.int64)
    f = pos - i0
    return prof[i0] * (1 - f) + prof[i0 + 1] * f


def crack_mask(h, w, zones, r, n_free=310, n_zone=420, ss=2):
    """Jagged fractures: random walks along the dip (a few across it), tapering at both ends."""
    img = Image.new("L", (w * ss, h * ss), 0)
    d = ImageDraw.Draw(img)
    phi = math.radians(PHI)

    def walk(x, y, ang0, length, width0, strength, depth=0):
        pts = [(x, y)]
        ang = ang0
        done = 0.0
        while done < length:
            step = float(r.uniform(5, 17))
            ang = ang0 + (ang - ang0) * 0.82 + float(r.normal(0, 0.17))
            if r.random() < 0.07:
                x += float(r.normal(0, 3.5))
            x += math.sin(ang) * step
            y += math.cos(ang) * step
            pts.append((x, y))
            done += step
        n = len(pts) - 1
        ph = float(r.uniform(0, 6.28))
        for i in range(n):
            t = (i + 0.5) / n
            env = math.sin(math.pi * t) ** 0.6 * (0.62 + 0.38 * math.sin(ph + t * length / 37.0))
            wd = max(1, int(round(width0 * (0.55 + 0.75 * env) * ss)))
            d.line([(pts[i][0] * ss, pts[i][1] * ss), (pts[i + 1][0] * ss, pts[i + 1][1] * ss)], fill=int(max(0, min(255, strength * env))), width=wd)
        if depth == 0 and r.random() < 0.35 and n > 6:
            bx, by = pts[int(r.integers(2, n - 2))]
            walk(bx, by, ang0 + float(r.choice([-1, 1])) * float(r.uniform(0.35, 0.8)), length * float(r.uniform(0.15, 0.4)), width0 * 0.8, strength * 0.8, 1)

    for _ in range(n_free):
        cross = r.random() < 0.2
        ang0 = (math.radians(-56) if cross else phi) + float(r.normal(0, 0.10))
        length = float(np.exp(r.uniform(math.log(110), math.log(1000)))) * (0.45 if cross else 1.0)
        walk(float(r.uniform(-80, w + 80)), float(r.uniform(-300, h)), ang0, length, float(r.uniform(0.7, 2.0)), float(r.uniform(110, 255)))
    for _ in range(n_zone):
        z = zones[int(r.integers(len(zones)))]
        v = float(r.uniform(z["v0"], z["v1"]))
        u = z["u"] + float(r.normal(0, z["s"] * 0.8))
        # (u, v) -> (x, y): u across the beds, v along them
        x = u * math.cos(phi) + v * math.sin(phi)
        y = -u * math.sin(phi) + v * math.cos(phi)
        ang0 = phi + float(r.normal(0, 0.22))
        walk(x, y, ang0, float(np.exp(r.uniform(math.log(40), math.log(260)))), float(r.uniform(0.7, 1.6)), float(r.uniform(90, 230)))
    for _ in range(300):  # the weathered top: short open joints, steep, across and flat
        kind = r.random()
        ang0 = (phi if kind < 0.5 else (math.radians(-56) if kind < 0.75 else math.radians(90))) + float(r.normal(0, 0.22))
        yy_ = TOP + float(r.uniform(150, 240)) + float(r.exponential(240))  # under the rubble
        walk(float(r.uniform(-40, w + 40)), yy_, ang0, float(np.exp(r.uniform(math.log(28), math.log(240)))), float(r.uniform(0.9, 2.4)), float(r.uniform(130, 255)), 1)
    m = np.asarray(img.resize((w, h), Image.BOX)).astype(np.float32) / 255.0
    return m


def vein_mask(h, w, r, n_veins=46, ss=2):
    """A few pale calcite veins: thin wavy lines across the beds, some with a short offshoot."""
    img = Image.new("L", (w * ss, h * ss), 0)
    d = ImageDraw.Draw(img)
    for i in range(n_veins):
        ang = math.radians(float(r.choice([-52.0, 58.0, -30.0])) + float(r.normal(0, 9)))
        x, y = float(r.uniform(-100, w + 100)), (i + float(r.uniform(0, 1))) * h / n_veins
        length = float(np.exp(r.uniform(math.log(260), math.log(1100))))
        wd = float(r.uniform(1.3, 3.4))
        k = float(r.uniform(150, 255))
        done, a_ = 0.0, ang
        while done < length:
            st_ = float(r.uniform(8, 22))
            a_ = ang + (a_ - ang) * 0.85 + float(r.normal(0, 0.10))
            nx, ny = x + math.sin(a_) * st_, y + math.cos(a_) * st_
            env = math.sin(math.pi * min(1.0, (done + st_ / 2) / length)) ** 0.5
            d.line([(x * ss, y * ss), (nx * ss, ny * ss)], fill=int(k * env), width=max(1, int(round(wd * (0.6 + 0.6 * env) * ss))))
            x, y, done = nx, ny, done + st_
    return gauss(np.asarray(img.resize((w, h), Image.BOX)).astype(np.float32) / 255.0, 0.6)


def structure(rock, r):
    """Bedding, fracture zones, cracks and slow tone drift, in place."""
    h, w, _ = rock.shape
    sphi, cphi = math.sin(math.radians(PHI)), math.cos(math.radians(PHI))
    off = h * sphi + 160
    n = int(off + w + 320)
    # the beds: a soft 1-D tone profile across the dip (no lines)
    bed = np.zeros(n, np.float32)
    for sc_, amp in ((70.0, 0.075), (26.0, 0.045), (9.0, 0.022)):
        bed += amp * noise1d(n, sc_, r)
    # broad fracture zones: ribbons along the dip
    zones = []
    for _ in range(11):
        v0 = float(r.uniform(-400, h))
        zones.append(dict(u=float(r.uniform(-h * sphi, w * cphi)), s=float(r.uniform(16, 46)), v0=v0, v1=v0 + float(r.uniform(900, 2600)), k=float(r.uniform(0.14, 0.30))))
    cracks = crack_mask(h, w, zones, r)
    # the big geology: broad beds of different value and colour, and a bold parting on most of their boundaries
    band_t = np.zeros(n, np.float32)
    band_c = np.zeros(n, np.float32)
    plane = np.zeros(n, np.float32)
    xi = np.arange(n, dtype=np.float32)
    u0 = 0.0
    while u0 < n:
        u1 = u0 + float(r.uniform(170, 430))
        band_t[int(u0) : int(u1)] = float(r.uniform(-0.15, 0.15))
        band_c[int(u0) : int(u1)] = float(r.uniform(-0.035, 0.035))
        if r.random() < 0.7:
            sg, dp = float(r.uniform(1.6, 3.0)), float(r.uniform(0.42, 0.68))
            lo, hi = int(max(0, u1 - 60)), int(min(n, u1 + 60))
            seg = xi[lo:hi]
            plane[lo:hi] += dp * np.exp(-0.5 * ((seg - u1) / sg) ** 2) + 0.13 * np.exp(-0.5 * ((seg - u1 + 9) / 9.0) ** 2) - 0.16 * np.exp(-0.5 * ((seg - u1 - 4.5) / 2.2) ** 2)
        u0 = u1
    band_t = gauss(band_t[None, :], 5.0)[0]
    band_c = gauss(band_c[None, :], 5.0)[0]
    veins = vein_mask(h, w, r)
    CH = 1264
    for y0 in range(0, h, CH):
        y1 = min(h, y0 + CH)
        hh = y1 - y0
        Y, X = np.mgrid[y0:y1, 0:w].astype(np.float32)

        # the same seed in every chunk and the chunk's y offset: the fields are continuous
        def rn(sa, sl, phi, seed):
            return rnoise(hh, w, sa, sl, phi, np.random.default_rng(seed), y0=y0)

        warp = 24 * rn(400, 520, PHI, 11) + 5 * rn(90, 170, PHI, 12)
        u = X * cphi - Y * sphi
        v = X * sphi + Y * cphi
        z = np.zeros((hh, w), np.float32)
        for zn in zones:
            if zn["v1"] < v.min() - 200 or zn["v0"] > v.max() + 200:
                continue
            along = smoothstep(zn["v0"], zn["v0"] + 300, v) * smoothstep(zn["v1"], zn["v1"] - 300, v)
            z = np.maximum(z, zn["k"] * along * np.exp(-0.5 * ((u + warp - zn["u"]) / zn["s"]) ** 2))
        z *= 0.75 + 0.25 * smoothstep(-1, 1, rn(40, 120, PHI, 14))
        ub = u + off + 34 * rn(800, 1500, PHI, 31) + 5 * rn(110, 300, PHI, 32)  # the big planes are nearly straight
        par = sample_profile(plane, ub) * (0.55 + 0.45 * smoothstep(-0.8, 0.3, rn(60, 700, PHI, 33)))  # a parting opens and closes along its run
        tone = 1.0 + 0.095 * rn(260, 950, PHI, 18) + 0.05 * rn(105, 380, PHI, 19) + sample_profile(bed, u + warp + off) + sample_profile(band_t, ub)
        tone = tone * (1.0 - par)
        wc = 0.02 * rn(320, 820, PHI, 20) + sample_profile(band_c, ub)
        ck = cracks[y0:y1]
        rim = np.maximum(np.roll(ck, 2, axis=1) - ck, 0)  # the lit lip of a crack
        blk = rock[y0:y1]
        blk -= 1.0
        blk *= (1.0 + 1.3 * z / 0.30)[..., None]  # more broken inside the zones
        blk += 1.0
        blk *= (tone * (1.0 - z) * (1.0 - 0.70 * ck) * (1.0 + 0.18 * rim))[..., None]
        blk[..., 0] *= 1.0 + wc
        blk[..., 2] *= 1.0 - wc
        vn = veins[y0:y1][..., None]  # calcite: pale, a little cool, over everything
        blk[:] = blk * (1 - 0.8 * vn) + np.array([1.5, 1.52, 1.55], np.float32) * (0.8 * vn)
    np.clip(rock, 0.03, 2.4, out=rock)


