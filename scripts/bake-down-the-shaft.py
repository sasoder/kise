def brush_colours(ref, box):
    """Tip and body colour of the clip's own brush in a box: its warm pixels, light and dark."""
    x0, y0, x1, y1 = box
    c = ref[y0:y1, x0:x1].reshape(-1, 3)
    warm = c[:, 0] - c[:, 2]
    c = c[warm > np.percentile(warm, 55)]
    L = c.mean(1)
    tip = c[L > np.percentile(L, 65)].mean(0)
    body = c[L < np.percentile(L, 35)].mean(0)
    return tip.astype(np.float32), (body.mean() + (body - body.mean()) * 0.7).astype(np.float32)


def draw_tuft(w, h, tip, body, r, lean, spread, dens, ss=3):
    """Dry brush: fine stems fanning up from one foot (or two), dark at the foot, pale at the tips."""
    wp, hp = w * ss, h * ss
    col = Image.new("RGB", (wp, hp), tuple(int(255 * v) for v in body))
    msk = Image.new("L", (wp, hp), 0)
    dc, dm = ImageDraw.Draw(col), ImageDraw.Draw(msk)
    feet = [wp * 0.5] if w < 100 else [wp * float(r.uniform(0.3, 0.4)), wp * float(r.uniform(0.6, 0.7))]
    stems = []
    for _ in range(int(dens * w * h / 8.0)):
        ang = float(np.clip(lean + r.normal(0, spread), -1.45, 1.45))
        ln = hp * float(r.uniform(0.3, 0.97)) * (1 - 0.35 * abs(ang - lean) / 1.45) * (1.0 if spread < 0.9 else 1.6)
        stems.append((float(r.random()), feet[int(r.integers(len(feet)))] + float(r.normal(0, 0.07 * wp)), ang, ln, float(r.normal(0, 0.5))))
    stems.sort()
    for depth, bx, ang, ln, curve in stems:
        t_ = tip * float(r.uniform(0.82, 1.12))
        f_ = body * float(r.uniform(0.6, 0.9))
        wdt = max(1, int(round(ss * float(r.uniform(0.7, 1.5)))))
        x, y = bx, hp - 2.0 * ss
        for k in range(7):
            t = (k + 1) / 7
            a_ = ang + curve * t * t
            nx, ny = x + math.sin(a_) * ln / 7, y - math.cos(a_) * ln / 7
            c = (f_ * (1 - t) + t_ * t) * (0.7 + 0.3 * depth)
            dc.line([(x, y), (nx, ny)], fill=tuple(int(255 * float(np.clip(v, 0, 1))) for v in c), width=wdt)
            dm.line([(x, y), (nx, ny)], fill=int(255 * (1.0 if t < 0.8 else 0.7)), width=wdt)
            x, y = nx, ny
    rgb = np.asarray(col.resize((w, h), Image.LANCZOS)).astype(np.float32) / 255.0
    m = np.asarray(msk.resize((w, h), Image.LANCZOS)).astype(np.float32) / 255.0
    return gauss(rgb, 0.9), np.clip(gauss(m, 0.9) * 1.25, 0, 1)  # as soft as the clip's own brush


