// Bakes Natural Earth boundaries into flat SVG path strings so the Remotion
// component stays dependency-free and deterministic at render time.
//
//   bun scripts/build-europe-map.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { geoConicConformal, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const OUT = "generated/components/europeMapData.ts";

// Frame the map inside the vertical 1080x1920 canvas.
const EXTENT = [
  [90, 470],
  [990, 1470],
];

// Greenland is Danish, so colouring it as context would say the opposite of
// what the map means — and at this projection it swallows the top-left corner.
const EXCLUDED = new Set(["Greenland"]);

// Everything outside this lon/lat window is dropped ring-by-ring, which removes
// the Azores, Canaries, Madeira, Svalbard and the French overseas departments
// before they can distort the projection fit.
const VIEW = { lon: [-26, 45], lat: [33, 72] };

// Geographic Europe, all of which runs publicly funded healthcare.
const HIGHLIGHTED = new Set([
  "Albania",
  "Andorra",
  "Austria",
  "Belarus",
  "Belgium",
  "Bosnia and Herz.",
  "Bulgaria",
  "Croatia",
  "Cyprus",
  "Czechia",
  "Denmark",
  "Estonia",
  "Finland",
  "France",
  "Germany",
  "Greece",
  "Hungary",
  "Iceland",
  "Ireland",
  "Italy",
  "Kosovo",
  "Latvia",
  "Liechtenstein",
  "Lithuania",
  "Luxembourg",
  "Malta",
  "Moldova",
  "Monaco",
  "Montenegro",
  "Macedonia",
  "N. Cyprus", // keeps the island of Cyprus reading as one shape
  "Netherlands",
  "Norway",
  "Poland",
  "Portugal",
  "Romania",
  "San Marino",
  "Serbia",
  "Slovakia",
  "Slovenia",
  "Spain",
  "Sweden",
  "Switzerland",
  "Ukraine",
  "United Kingdom",
  "Vatican",
]);

const load = (file) => {
  const topo = JSON.parse(readFileSync(`node_modules/world-atlas/${file}`, "utf8"));
  return feature(topo, topo.objects.countries).features;
};

const ringInView = (ring) => {
  let minLon = Infinity;
  let maxLon = -Infinity;
  let minLat = Infinity;
  let maxLat = -Infinity;
  for (const [lon, lat] of ring) {
    if (lon < minLon) minLon = lon;
    if (lon > maxLon) maxLon = lon;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
  }
  return (
    maxLon >= VIEW.lon[0] &&
    minLon <= VIEW.lon[1] &&
    maxLat >= VIEW.lat[0] &&
    minLat <= VIEW.lat[1]
  );
};

const clipToView = (geometry) => {
  const polygons =
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  const kept = polygons.filter((rings) => ringInView(rings[0]));
  if (kept.length === 0) return null;
  return { type: "MultiPolygon", coordinates: kept };
};

const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));

const atlas = load("countries-50m.json");

const highlighted = [];
for (const f of atlas) {
  if (!HIGHLIGHTED.has(f.properties.name)) continue;
  const geometry = clipToView(f.geometry);
  if (geometry) highlighted.push({ name: f.properties.name, geometry });
}

const missing = [...HIGHLIGHTED].filter(
  (name) => !highlighted.some((c) => c.name === name),
);
if (missing.length) {
  console.warn(`Not found in the 50m atlas: ${missing.join(", ")}`);
}

const context = [];
for (const f of atlas) {
  if (HIGHLIGHTED.has(f.properties.name)) continue;
  if (EXCLUDED.has(f.properties.name)) continue;
  const geometry = clipToView(f.geometry);
  if (geometry) context.push({ name: f.properties.name, geometry });
}

// Fit the projection to the lon/lat window rather than to the countries, so the
// framing is stable no matter which shapes survive the clip.
const projection = geoConicConformal()
  .parallels([43, 62])
  .rotate([-10, 0])
  .center([0, 52]);

// Fit to the highlighted countries as a point cloud. A Polygon or MultiPolygon
// here would be ambiguous — d3 reads ring winding spherically, and the wrong
// direction means "the whole globe except this shape", which collapses the fit
// to a single pixel.
const fitPoints = highlighted.flatMap(({ geometry }) =>
  geometry.coordinates.flatMap((rings) => rings[0]),
);

projection.fitExtent(EXTENT, { type: "MultiPoint", coordinates: fitPoints });

const path = geoPath(projection);

const serialize = (entries) =>
  entries
    .map(({ name, geometry }) => ({
      name,
      d: round(path(geometry) ?? ""),
      centroid: path.centroid(geometry).map((n) => Math.round(n * 10) / 10),
    }))
    .filter((c) => c.d.length > 0 && Number.isFinite(c.centroid[0]));

const highlightedOut = serialize(highlighted).sort((a, b) => a.centroid[0] - b.centroid[0]);
const contextOut = serialize(context);

const body = `// Generated by scripts/build-europe-map.mjs — do not edit by hand.
// Natural Earth boundaries (public domain) projected to a 1080x1920 canvas.

export type MapShape = {
  name: string;
  d: string;
  centroid: [number, number];
};

/** Countries with publicly funded healthcare, ordered west to east for the sweep. */
export const europeCountries: MapShape[] = ${JSON.stringify(highlightedOut, null, 2)};

/** Surrounding landmass, drawn dim so the highlighted countries read as a map. */
export const contextLand: MapShape[] = ${JSON.stringify(contextOut, null, 2)};
`;

writeFileSync(OUT, body);
console.log(
  `Wrote ${OUT}: ${highlightedOut.length} highlighted, ${contextOut.length} context shapes.`,
);
