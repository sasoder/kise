// Bakes NobodyCanSettle's vector geometry on the ww1 projection, measured off
// EverybodyWants' Dalmatia want (WANT_D.dalmatia, ww1Overlay.ts, read-only):
// the settlement line's two limits, the point the two desire-arrows aim at,
// and Belgrade. Writes one file of its own.
//
//   bun scripts/build-settle-geometry.mjs [--debug out.png]
//
// Writes generated/components/settleGeometry.ts:
//   INLAND   s = -1: just inland of the Dalmatian strip (the coast on Italy's,
//            seaward, side of the line)
//   COAST    s = +1: just seaward of the outer islands' outline (the coast on
//            Serbia's, inland, side)
//   AXIS_D / AXIS_N  the chord NW -> SE and its inland normal
//   TARGET   where both arrows point: the Dalmatian mainland between Sebenico
//            and Knin (16.1 E, 43.72 N), checked to lie inside the want
//   BELGRADE (the ww1 overlay has only the great-power capitals)
// Both limits are sampled at the same N stations along the chord (Istrian end
// -> Montenegrin end), ~14 world px past the strip at each end. Method: every
// vertex of the want in chord coordinates (t along, o inland); per station the
// max / min o over a +-5 px window, pushed out by a margin, then smoothed and
// re-clamped in alternation so the smoothing never cuts back into the strip.

import { writeFileSync } from "node:fs";
import { geoAzimuthalEqualArea } from "d3-geo";
import { WANT_D } from "../generated/components/ww1Overlay.ts";

// -- the ww1 projection, exactly as scripts/build-ww1-map.mjs builds it ------------
const projection = geoAzimuthalEqualArea().rotate([-15, -25]).scale(1).translate([0, 0]);
{
  const a = projection([-10.5, 53.5]);
  const b = projection([50, 53.5]);
  projection.scale(1080 / Math.hypot(b[0] - a[0], b[1] - a[1]));
  const c = projection([19.75, 53.5]);
  projection.translate([540 - c[0], 835 - c[1]]);
}
const r2 = (v) => Math.round(v * 100) / 100;
const P = (ll) => {
  const [x, y] = projection(ll);
  return { x: r2(x), y: r2(y) };
};
const BELGRADE = P([20.46, 44.8]);
const TARGET = P([16.1, 43.72]);

// -- the Dalmatia want, as rings of points --------------------------------------------
const rings = WANT_D.dalmatia
  .split("Z")
  .filter(Boolean)
  .map((r) => [...r.matchAll(/[ML]([-0-9.]+),([-0-9.]+)/g)].map((m) => [+m[1], +m[2]]));
const pts = rings.flat();
const inside = (x, y) => {
  let c = false;
  for (const r of rings)
    for (let i = 0, j = r.length - 1; i < r.length; j = i++)
      if (r[i][1] > y !== r[j][1] > y && x < ((r[j][0] - r[i][0]) * (y - r[i][1])) / (r[j][1] - r[i][1]) + r[i][0]) c = !c;
  return c;
};
if (!inside(TARGET.x, TARGET.y)) throw new Error("TARGET is not inside the Dalmatia want");

// -- the chord and the two limits ------------------------------------------------------------
const A = P([14.75, 45.12]);
const B = P([19.2, 41.95]);
const L = Math.hypot(B.x - A.x, B.y - A.y);
const d = [(B.x - A.x) / L, (B.y - A.y) / L];
const n = [d[1], -d[0]]; // screen y is down: (dy, -dx) points north-east, inland
const tc = pts.map(([x, y]) => [(x - A.x) * d[0] + (y - A.y) * d[1], (x - A.x) * n[0] + (y - A.y) * n[1]]);
const tMin = Math.min(...tc.map((p) => p[0]));
const tMax = Math.max(...tc.map((p) => p[0]));
const N = 72;
const EXT = 14;
const t0 = tMin - EXT;
const t1 = tMax + EXT;
const WIN = 5;
const MARGIN_IN = 1.5;
const MARGIN_OUT = 1.2; // the outer islands' outline, not beyond
const T = Array.from({ length: N }, (_, i) => t0 + ((t1 - t0) * i) / (N - 1));
const env = (sign) =>
  T.map((t) => {
    const tt = Math.max(tMin + 2, Math.min(tMax - 2, t));
    let best = null;
    for (const [pt, po] of tc) if (Math.abs(pt - tt) <= WIN) best = best === null ? po : sign > 0 ? Math.max(best, po) : Math.min(best, po);
    return best;
  });
const raw = { in: env(1).map((v) => v + MARGIN_IN), out: env(-1).map((v) => v - MARGIN_OUT) };
const smooth = (a, r, passes) => {
  let v = a.slice();
  for (let p = 0; p < passes; p++)
    v = v.map((_, i) => {
      let s = 0;
      let w = 0;
      for (let j = -r; j <= r; j++) {
        const q = Math.max(0, Math.min(v.length - 1, i + j));
        const wt = r + 1 - Math.abs(j);
        s += v[q] * wt;
        w += wt;
      }
      return s / w;
    });
  return v;
};
let inO = smooth(raw.in, 3, 3);
let outO = smooth(raw.out, 3, 3);
for (let it = 0; it < 40; it++) {
  inO = smooth(inO.map((v, i) => Math.max(v, raw.in[i])), 3, 1);
  outO = smooth(outO.map((v, i) => Math.min(v, raw.out[i])), 3, 1);
}
const toW = (t, o) => [r2(A.x + t * d[0] + o * n[0]), r2(A.y + t * d[1] + o * n[1])];
const INLAND = T.map((t, i) => toW(t, inO[i]));
const COAST = T.map((t, i) => toW(t, outO[i]));

writeFileSync(
  "generated/components/settleGeometry.ts",
  `// Generated by scripts/build-settle-geometry.mjs — do not edit by hand.
// NobodyCanSettle's vectors on the ww1 projection (Lambert azimuthal
// equal-area 15 E, 25 N; world px), measured off WANT_D.dalmatia.
export type P2 = [number, number];
export const BELGRADE = ${JSON.stringify(BELGRADE)};
/** Where both desire-arrows point: the Dalmatian mainland (16.1 E, 43.72 N). */
export const TARGET = ${JSON.stringify(TARGET)};
/** The chord NW -> SE and its inland (north-east) normal. */
export const AXIS_D: P2 = ${JSON.stringify(d.map((v) => +v.toFixed(5)))};
export const AXIS_N: P2 = ${JSON.stringify(n.map((v) => +v.toFixed(5)))};
/** s = -1: just inland of the Dalmatian strip. */
export const INLAND: P2[] = ${JSON.stringify(INLAND)};
/** s = +1: just seaward of the outer islands. */
export const COAST: P2[] = ${JSON.stringify(COAST)};
`,
);
console.log(`BELGRADE ${JSON.stringify(BELGRADE)} TARGET ${JSON.stringify(TARGET)}; ${N} stations`);

const dbg = process.argv.indexOf("--debug");
if (dbg > 0) {
  const { Resvg } = await import("@resvg/resvg-js");
  const { LAND_D } = await import("../generated/components/ww1MapData.ts");
  const line = (a, c) => `<path d="M${a.map((p) => p.join(",")).join("L")}" fill="none" stroke="${c}" stroke-width="0.6"/>`;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="1400" viewBox="420 1060 160 140">
<rect x="0" y="0" width="3000" height="3000" fill="#1B2226"/>
<path d="${LAND_D}" fill="#3F3428" fill-rule="evenodd"/>
<path d="${WANT_D.dalmatia}" fill="#FFB000" fill-opacity="0.5" fill-rule="evenodd"/>
${line(INLAND, "#fff")}${line(COAST, "#0ff")}
<circle cx="${TARGET.x}" cy="${TARGET.y}" r="1" fill="#f0f"/>
</svg>`;
  writeFileSync(process.argv[dbg + 1], new Resvg(svg).render().asPng());
}
