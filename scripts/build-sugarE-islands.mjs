// Bakes the three islands Britain KEPT for cut E (KeepTheCaribbean) of the clip
// "SarahWar_Britain_let_America_go_to_keep_its_sugar_islands": Jamaica, Antigua
// (+ Barbuda, its dependency) and Barbados, as land-only svg paths in the sugar world's
// world px (Mercator, identical to scripts/build-sugar-map.mjs), with their centroids.
// Also checks the clearance of cut E's sea routes (sugarEData.ts ROUTES_LL) from land.
//
//   bun scripts/build-sugarE-islands.mjs
//
// Source: Natural Earth 10m admin-0 countries (public domain) via the installed
// world-atlas (countries-10m.json, land-10m.json).
// Why only these three: they were British through the whole war (never taken);
// Dominica, St Vincent, Grenada, Tobago, St Kitts, Nevis, Montserrat and the Bahamas
// all fell in 1778-82 (notes/E_FACTS.md).
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const OUT = "generated/components/sugarEIslands.ts";
const PPD = 40;
const LON0 = -110;
const M = (lat) => (Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360)) * 180) / Math.PI;
const MERC_TOP = M(68);
const P = ([lon, lat]) => [PPD * (lon - LON0), PPD * (MERC_TOP - M(lat))];
const r2 = (v) => Math.round(v * 100) / 100;

const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-10m.json", "utf8"));
const countries = feature(topo, topo.objects.countries).features;
const byName = (n) => {
  const f = countries.find((q) => q.properties.name === n);
  if (!f) throw new Error(`no country ${n}`);
  return f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
};
const ringArea = (r) => {
  let a = 0;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) a += (r[j][0] + r[i][0]) * (r[j][1] - r[i][1]);
  return a / 2;
};
const ringCentroid = (r) => {
  let a = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const f = r[j][0] * r[i][1] - r[i][0] * r[j][1];
    a += f;
    cx += (r[j][0] + r[i][0]) * f;
    cy += (r[j][1] + r[i][1]) * f;
  }
  return [cx / (3 * a), cy / (3 * a)];
};
const mpD = (polys) =>
  polys
    .map((poly) => poly.map((ring) => "M" + ring.map(([x, y]) => `${r2(x)},${r2(y)}`).join("L") + "Z").join(""))
    .join("");

const island = (name, keep = () => true) => {
  const polys = byName(name)
    .filter((poly) => keep(poly[0]))
    .map((poly) => poly.map((ring) => ring.map(P)));
  const main = polys.slice().sort((a, b) => Math.abs(ringArea(b[0])) - Math.abs(ringArea(a[0])))[0];
  const c = ringCentroid(main[0]);
  const xs = polys.flatMap((p) => p[0].map((q) => q[0]));
  const ys = polys.flatMap((p) => p[0].map((q) => q[1]));
  return {
    d: mpD(polys),
    c: [r2(c[0]), r2(c[1])],
    box: { x0: r2(Math.min(...xs)), y0: r2(Math.min(...ys)), x1: r2(Math.max(...xs)), y1: r2(Math.max(...ys)) },
  };
};
const ISLANDS = {
  jamaica: island("Jamaica"),
  antigua: island("Antigua and Barb."),
  barbados: island("Barbados"),
};

// route clearance from land (sea routes should keep off the coast where they can)
const land = JSON.parse(readFileSync("node_modules/world-atlas/land-10m.json", "utf8"));
const landF = feature(land, land.objects.land);
const landPolys = (landF.features ?? [landF]).flatMap((f) => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates));
const inPoly = ([x, y], poly) => {
  let c = false;
  for (const r of poly)
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i];
      const [xj, yj] = r[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
    }
  return c;
};
const near = landPolys.filter((poly) => poly[0].some(([x, y]) => x > -80 && x < -55 && y > 10 && y < 42));
const src = readFileSync("generated/components/sugarEData.ts", "utf8");
const block = src.slice(src.indexOf("ROUTES_LL"));
for (const name of ["trunk", "west", "east"]) {
  const m = block.match(new RegExp(`${name}: \\[([^\\]]*(?:\\][^\\]]*)*?)\\],\\n`));
  if (!m) continue;
  const pts = [...m[1].matchAll(/\[(-?[\d.]+), (-?[\d.]+)\]/g)].map((q) => [+q[1], +q[2]]);
  let wet = 0;
  let dry = [];
  for (let i = 1; i < pts.length; i++)
    for (let t = 0; t < 1; t += 0.02) {
      const p = [pts[i - 1][0] + (pts[i][0] - pts[i - 1][0]) * t, pts[i - 1][1] + (pts[i][1] - pts[i - 1][1]) * t];
      if (near.some((poly) => inPoly(p, poly))) dry.push(p.map((v) => v.toFixed(2)).join(","));
      else wet++;
    }
  console.log(`${name}: ${wet} sea samples, ${dry.length} on land${dry.length ? `: ${dry.slice(0, 12).join(" ")}` : ""}`);
}

const HEAD = `// GENERATED by scripts/build-sugarE-islands.mjs - do not edit.
// The three islands Britain kept through the war (Jamaica, Antigua + Barbuda, Barbados),
// Natural Earth 10m (public domain) via world-atlas, in the sugar world's world px.
`;
writeFileSync(OUT, `${HEAD}export const ISLANDS = ${JSON.stringify(ISLANDS)} as const;\n`);
console.log(`wrote ${OUT}`, Object.fromEntries(Object.entries(ISLANDS).map(([k, v]) => [k, { c: v.c, box: v.box, chars: v.d.length }])));
