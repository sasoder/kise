#!/usr/bin/env python3
"""Trace the Mercedes-AMG PETRONAS F1 Team lockup (the user's PNG/WebP, ink on transparent) into one
even-odd SVG path for the cheeky-pint tile knock-out, and write
generated/components/kits/cheeky-pint/mercedesF1Logo.ts.

No tracer is installed, so this is a small one: the alpha upscaled 3x (bicubic) and thresholded at 0.5,
every pixel crack between ink and paper linked into closed loops (ink on the left), each loop
simplified by Ramer-Douglas-Peucker. All ink (black and the teal PETRONAS) is one figure: the tiles
draw logos in one tone.

  python3 scripts/clips/toto-mercedes-job/trace-f1-team-logo.py
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "assets-src/toto-mercedes-job/mercedes-amg-petronas-f1-team-logo.webp"
OUT = ROOT / "generated/components/kits/cheeky-pint/mercedesF1Logo.ts"
UP = 3  # supersampling before the threshold
EPS = 0.45  # RDP tolerance, source px


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    a, b = pts[0], pts[-1]
    ab = b - a
    n = np.hypot(*ab)
    d = np.abs(ab[0] * (pts[:, 1] - a[1]) - ab[1] * (pts[:, 0] - a[0])) / n if n > 1e-9 else np.hypot(*(pts - a).T)
    i = int(np.argmax(d))
    if d[i] <= eps:
        return np.array([a, b])
    return np.vstack([rdp(pts[: i + 1], eps)[:-1], rdp(pts[i:], eps)])


def loops(ink):
    h, w = ink.shape
    p = np.pad(ink, 1)
    nxt = {}  # directed crack edges, ink on the right (y down): start vertex -> list of end vertices
    # horizontal cracks between rows y-1 and y
    for y in range(h + 1):
        up, dn = p[y, 1:-1], p[y + 1, 1:-1]
        for x in np.nonzero(dn & ~up)[0]:  # ink below: run left -> right
            nxt.setdefault((x, y), []).append((x + 1, y))
        for x in np.nonzero(up & ~dn)[0]:  # ink above: run right -> left
            nxt.setdefault((x + 1, y), []).append((x, y))
    for x in range(w + 1):
        lf, rt = p[1:-1, x], p[1:-1, x + 1]
        for y in np.nonzero(lf & ~rt)[0]:  # ink on the left: run top -> bottom
            nxt.setdefault((x, y), []).append((x, y + 1))
        for y in np.nonzero(rt & ~lf)[0]:  # ink on the right: run bottom -> top
            nxt.setdefault((x, y + 1), []).append((x, y))
    out = []
    while nxt:
        start = next(iter(nxt))
        loop = [start]
        cur, prev_dir = start, None
        while True:
            cands = nxt[cur]
            if len(cands) == 1 or prev_dir is None:
                nv = cands[0]
            else:  # a saddle: take the sharpest turn of one hand so loops never cross
                def turn(v):
                    d = (v[0] - cur[0], v[1] - cur[1])
                    return prev_dir[0] * d[1] - prev_dir[1] * d[0]
                nv = max(cands, key=turn)
            cands.remove(nv)
            if not cands:
                del nxt[cur]
            prev_dir = (nv[0] - cur[0], nv[1] - cur[1])
            cur = nv
            if cur == start:
                break
            loop.append(cur)
        out.append(np.array(loop, dtype=float))
    return out


def main():
    im = Image.open(SRC).convert("RGBA")
    a = im.getchannel("A")
    W, H = im.size
    big = np.asarray(a.resize((W * UP, H * UP), Image.BICUBIC), dtype=np.float32) / 255
    ink = big >= 0.5
    ys, xs = np.nonzero(ink)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    parts = []
    n_pts = 0
    for lp in loops(ink):
        if len(lp) < 8:
            continue
        pts = lp / UP
        # RDP on a closed loop: split at the point farthest from the first
        j = int(np.argmax(np.hypot(*(pts - pts[0]).T)))
        s = np.vstack([rdp(pts[: j + 1], EPS)[:-1], rdp(np.vstack([pts[j:], pts[:1]]), EPS)[:-1]])
        n_pts += len(s)
        parts.append("M" + "L".join(f"{x:g} {y:g}" for x, y in np.round(s, 1)) + "Z")
    d = "".join(parts)
    bx, by, bw, bh = x0 / UP, y0 / UP, (x1 - x0) / UP, (y1 - y0) / UP
    fill = float(ink[y0:y1, x0:x1].mean())
    # centroid offset from the box centre, in units of the box's geometric mean (stoutShared OPTICAL)
    cy = float(((ys.mean() - (y0 + y1) / 2) / UP) / np.sqrt(bw * bh))
    OUT.write_text(
        "// GENERATED by scripts/clips/toto-mercedes-job/trace-f1-team-logo.py — do not edit by hand.\n"
        "// The Mercedes-AMG PETRONAS F1 Team lockup (star, AMG, PETRONAS, FORMULA 1 TEAM), supplied by the user\n"
        "// (assets-src/toto-mercedes-job/mercedes-amg-petronas-f1-team-logo.webp), traced to one even-odd path\n"
        "// in source px. All ink is one tone (the tiles knock the figure out). Inlined: never an <image>.\n"
        f"export const MERC_F1_VIEW = {{ w: {W}, h: {H} }} as const;\n"
        f"/** The ink box [x, y, w, h], its silhouette fill and centroid offset (stoutShared's OPTICAL terms). */\n"
        f"export const MERC_F1_OPTICAL = {{ box: [{bx:.2f}, {by:.2f}, {bw:.2f}, {bh:.2f}] as [number, number, number, number], fill: {fill:.3f}, cy: {cy:.3f} }};\n"
        f'export const MERC_F1_D =\n  "{d}";\n'
    )
    print(f"{len(parts)} loops, {n_pts} points, {len(d) / 1024:.1f} KB; box {bx:g},{by:g} {bw:g}x{bh:g}; fill {fill:.3f}; cy {cy:.3f}", file=sys.stderr)


if __name__ == "__main__":
    main()
