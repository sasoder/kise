    c.rect(lx - 2.5, ly - 4.3, lx + 2.5, ly - 3.2, dark_tin, amb=0.3, lampf=0.2)
    c.rect(lx - 2.2, ly + 3.0, lx + 2.2, ly + 4.4, dark_tin, amb=0.3, lampf=0.2)
    for sx_ in (-2.0, 1.7):
        c.rect(lx + sx_, ly - 3.2, lx + sx_ + 0.3, ly + 3.0, dark_tin, amb=0.3, lampf=0.2)

    cov = np.clip(c.cov, 0, 1)

    # ---- light
    L_old, _ = lamp_fall(X, Y, g["lamp"], st["lamp_r"], st["lamp_k"])
    L_new, d2 = lamp_fall(X, Y, g["lamp"], CAMP_R, CAMP_K)
    core = np.exp(-(((X - lx) / 1.25) ** 2 + ((Y - ly) / 2.3) ** 2) / 2)
    haze = 0.20 * np.exp(-np.sqrt(d2) / 16.0)
    emit = (core[..., None] * np.array([1.0, 0.86, 0.60], np.float32) + haze[..., None] * np.array([0.85, 0.50, 0.20], np.float32)) * CAMP_K
    amb_col = LAMP[None, None, :]

    # what the plate's rock got from the plate's lamp, so it can be taken out and put back
    prox = gauss_big(m, 11.0 * S) * (1 - m)
    den = amb_col + WARM[None, None, :] * (L_old * 0.5 * prox)[..., None]

    # the shaft above and below the station: its timbering re-drawn at this scale, the plate's own light on it
    SX0, SX1 = 475, 585
    syn, syn_a = synth_shaft(SX0, WY0, SX1, WY1, S, sets, np.random.default_rng(7003), timber, lagging)
    out_rows = np.clip(sm(-1.0, 1.0, (g["r0"] + 24.0) - Y) + sm(-1.0, 1.0, Y - (yfw + 2.0)), 0, 1)  # above the station's roof, below its floor
    ox = int(round((SX0 - X0) * S))
    ssl = (slice(None), slice(ox, ox + syn.w))
    sa = np.zeros((h, w), np.float32)
    sa[ssl] = syn_a * out_rows
    del syn_a

    tin = (c.lampf < 0.22) & (c.cov > 0.5) & (np.abs(X - lx) < 3.2) & (np.abs(Y - ly) < 6.0)
    emit_in = emit * (1.0 - 0.9 * gauss(tin.astype(np.float32), 0.6))[..., None]

    def lit(level, head=False):
        outside = U * (amb_col + WARM[None, None, :] * (level * L_new * 0.5 * prox)[..., None]) / den
        if head:
            shaft = syn.alb * (HEAD[None, None, :] * syn.hl[..., None] + 0.5 * amb_col * syn.amb[..., None])
            inside = c.alb * (amb_col * c.amb[..., None] + HEAD[None, None, :] * (0.3 * c.lampf)[..., None])
        else:
            shaft = syn.alb * (amb_col * syn.amb[..., None] + WARM[None, None, :] * (level * L_new[ssl] * syn.lampf)[..., None])
            inside = c.alb * (amb_col * c.amb[..., None] + WARM[None, None, :] * (level * L_new * c.lampf)[..., None]) + emit_in * level
        outside[ssl] = outside[ssl] * (1 - sa[ssl][..., None]) + shaft * sa[ssl][..., None]
        o = outside * (1 - cov[..., None]) + inside * cov[..., None]
        t = tone(o)
        k = np.clip(gauss(np.maximum(cov, sa), 3.0) * 4.0, 0, 1)[..., None]  # only what was re-drawn gets the plate's softness again
        return t * (1 - k) + gauss(t, 1.15) * k

    a0, a1 = int(round((ON0 - WY0) * S)), int(round((ON1 - WY0) * S))
    off = lit(EMBER)
    save_jpg(off, "fd_station_off.jpg", 90)
