def bake_collar(P, CAP, det_src, rock_src, gravel_src, sets, timber, lagging, check):
    S = 2.6
    X0, X1, WY0, WY1 = 300, 760, -320, 1200
    r = np.random.default_rng(7101)
    rows = WY1 - WY0
    capn = CAP.shape[0]
    cap0 = -TOP - WY0  # row of the cap's first row
    # the ground in front of the cut, continued upward: the cap's own recipe (the clip's gravel)
    gh = PLATE_Y0 - WY0
    ground = dts.collage(gh, W, gravel_src, r, tile=170, step=115, blob=(200, 150), blob_step=(120, 100), skip=(0.0, 0.3), scale_range=(1.0, 1.3))
    ground = ground / np.maximum(gauss_big(ground.mean(2), 22.0), 0.2)[..., None]
    ground = ground * GRAVEL * (1.0 + 0.03 * vnoise(gh, W, 110, 36, r))[..., None]
    for _ in range(60):  # a few pale stones lying on it, each with its shadow
        cx, sz = float(r.uniform(6, W - 6)), float(np.exp(r.uniform(math.log(1.6), math.log(5.0))))
        cy = float(r.uniform(8, gh - 8))
        R = int(sz + 5)
        x0, y0 = int(cx) - R, int(cy) - R
        if x0 < 0 or y0 < 0 or x0 + 2 * R + 1 > W or y0 + 2 * R + 1 > gh:
            continue
        yy_, xx_ = np.mgrid[y0 : y0 + 2 * R + 1, x0 : x0 + 2 * R + 1].astype(np.float32)
        mm = sm(1.25, 0.75, np.sqrt(((xx_ - cx) / sz) ** 2 + ((yy_ - cy) / (sz * 0.62)) ** 2))
        sh = 0.30 * sm(1.5, 0.6, np.sqrt(((xx_ - cx - 0.3 * sz) / (sz * 1.15)) ** 2 + ((yy_ - cy - 0.55 * sz) / (sz * 0.6)) ** 2))
        dst = (slice(y0, y0 + 2 * R + 1), slice(x0, x0 + 2 * R + 1))
        g_ = ground[dst] * (1 - sh * (1 - mm))[..., None]
        ground[dst] = g_ * (1 - mm[..., None]) + (GRAVEL * float(r.uniform(1.18, 1.5)) * np.array([1.06, 1.0, 0.95], np.float32)) * mm[..., None]
    ground = gauss(ground, 0.7)

    comp = np.zeros((rows, W, 3), np.float32)
    comp[:gh] = ground
    comp[gh:] = P[: rows - gh]
    a = CAP[..., 3:4]
    comp[cap0 : cap0 + capn] = CAP[..., :3] * a + comp[cap0 : cap0 + capn] * (1 - a)
    comp = comp[:, X0:X1]

    # one tuft of the cap's brush (plate x 632..704) is cut off square along the right edge of its box: enlarged, a
    # hard vertical line. Its last 16 px go over into the ground behind it (and the ground just beyond into the same).
    for x in range(688, 721):
        wgt = float(sm(688.0, 703.0, x) * sm(720.0, 705.0, x))
        r_top, r_bot = cap0 + TOP - 130, cap0 + TOP - 34
        comp[r_top:r_bot, x - X0] = comp[r_top:r_bot, x - X0] * (1 - wgt) + ground[r_top:r_bot, x] * wgt

    # the lip: the cap's edge wobbles by a px every few px, which enlarged 2.6 times is a row of saw teeth.
    # Find it (the first strong step from ground to dark soil going down) and smooth a thin band along it sideways.
    Lc = gauss(comp.mean(2), 1.0)
    r_a, r_b = cap0 + TOP - 70, cap0 + TOP + 60
    step = Lc[r_a - 3 : r_b - 3] - Lc[r_a + 3 : r_b + 3]  # ground above (light) minus what is 6 px under it
    edge = r_a + np.argmax(step, axis=0).astype(np.float32)
    edge = gauss(edge[None, :], 3.0)[0]
    rr = np.arange(rows, dtype=np.float32)[:, None]
    band = np.exp(-0.5 * ((rr - edge[None, :]) / 3.2) ** 2) * (np.abs(np.arange(comp.shape[1]) + X0 - SHAFT_X) > 62)[None, :]
    side = comp.copy()
    kx = np.exp(-0.5 * (np.arange(-7, 8) / 2.6) ** 2).astype(np.float32)
    kx /= kx.sum()
    pad_ = np.pad(comp, ((0, 0), (7, 7), (0, 0)), mode="edge")
    side[:] = sum(kx[i] * pad_[:, i : i + comp.shape[1]] for i in range(15))
    comp = comp * (1 - 0.85 * band[..., None]) + side * (0.85 * band[..., None])

    U = upscale(comp, S)
    U = resharpen(U, 2.8, 0.85)
    h, w = U.shape[:2]
    Yw = (np.arange(h, dtype=np.float32) + 0.5) / S + WY0
    # the detail belongs to the cut face, not to the ground in front of it (the footage's gravel is soft)
    det = rock_detail(h, w, rock_src, det_src, r, 1.1, 0.30, 0.18)
    lipk = sm(-40.0, 20.0, Yw)[:, None] * (0.25 + 0.75 * sm(40.0, 240.0, Yw)[:, None]) + 0.2 * sm(-40.0, 20.0, Yw)[:, None] * (1 - sm(40.0, 240.0, Yw)[:, None])
    U *= (1.0 + (det - 1.0) * lipk)[..., None]
    del det
    U = np.clip(U, 0, 1)
    # the ground runs on up the frame: further from the cut it goes out of focus and into the dusk
    far = np.clip((-112.0 - Yw) / 150.0, 0.0, 1.0)
    if far.max() > 0:
        n_far = int((far > 0).sum()) + 40
        top = U[:n_far]
        lv = [top, gauss(top, 2.5), gauss_big_rgb(top, 6.0), gauss_big_rgb(top, 12.0)]
        f = far[:n_far, None, None] ** 0.8 * 3.0
        out = np.zeros_like(top)
        for i in range(4):
            out += lv[i] * np.clip(1.0 - np.abs(f - i), 0.0, 1.0)
        dark = 1.0 - 0.62 * far[:n_far, None, None] ** 1.25
        cool = np.array([0.94, 0.99, 1.04], np.float32)[None, None, :] ** far[:n_far, None, None]
        U[:n_far] = out * dark * cool

    # the shaft's timbering re-drawn at this scale: in the dusk and our own light (the base), and under his headlamp
    LX0, LX1 = 475, 585
    syn, syn_a = synth_shaft(LX0, WY0, LX1, WY1, S, sets, np.random.default_rng(7102), timber, lagging)
