    m[(Y[:, 0] < g["r0"] - 2) | (Y[:, 0] > g["r0"] + g["nr"] + 2)] = 0.0
    v = np.clip((Y - roof[None, :]) / np.maximum(floor - roof, 1)[None, :], 0, 1)
    z_roof = sm(0.26, 0.05, v)
    z_floor = sm(0.76, 0.95, v)
    ao = 0.5 + 0.5 * np.maximum(np.sin(np.pi * v), 0) ** 0.5

    # the back wall: the same piece of rock as in the plate (the plate's own rock from under the sump, un-lit)
    spare = untone(P[9320 - PLATE_Y0 : 9560 - PLATE_Y0]) / LAMP[None, None, :]
    back = spare[g["so"] : g["so"] + g["nr"], g["sx"] : g["sx"] + n].copy()
    if g["flip"]:
        back = back[:, ::-1]
    back = 1.0 + (back / np.maximum(back.mean(), 1e-3) - 1.0) * 1.5
    back = np.clip(back, 0.25, 2.2) * ROCK_ALBEDO.mean() * np.array([1.0, 0.98, 0.95], np.float32)
    padc = 0
    back = np.pad(back, ((0, 0), (0, padc), (0, 0)), mode="edge")
    muck1 = np.pad(g["muck"], ((0, 0), (0, padc)), mode="edge")
    back_hi = resharpen(upscale(back, S), 5.0, 1.1)
    muck_hi = upscale(muck1, S)
    bh, bwf = back_hi.shape[:2]
    back_hi *= rock_detail(bh, bwf, rock_src, det_src, r, 1.5, 0.7, 0.45, 0.32)[..., None]
    # the block of the whole opening, cut to the box
    bx0 = int(round((cols[0] - X0) * S))
    by0 = int(round((g["r0"] - WY0) * S))
    sx0, dx0 = max(0, -bx0), max(0, bx0)
    bw = min(bwf - sx0, w - dx0)
    back_hi = back_hi[:, sx0 : sx0 + bw]
    muck_hi = muck_hi[:, sx0 : sx0 + bw]
    bsl = (slice(by0, by0 + bh), slice(dx0, dx0 + bw))
    mk = 1.0 + z_floor[bsl] * (0.25 + 0.4 * (0.75 * muck_hi + 0.5 * vnoise(bh, bw, 2.2, 1.6, r)))
    back_hi = back_hi * ((1.0 - 0.40 * z_roof[bsl]) * mk)[..., None]
    far = 1.0 - 0.6 * sm(0.15, 1.0, dl / length)
    c.alb[bsl] = back_hi
    c.amb[:] = 0.21 * far * ao
    c.lampf[:] = ao
    c.cov[:] = m

    # timber sets along the drift, the shaft's cap and sill
    lamp_x = g["lamp"][0]
    for p in g["posts"]:
        away = 1.0 if p["x"] > lamp_x else -1.0
        # its shadow on the back wall, on the side away from the lamp
        dxs = (X - (p["x"] + away * p["pw"] / 2)) * away
        rows_in = sm(-1.0, 1.0, Y - (p["ytop"] - p["ch"])) * sm(-1.0, 1.0, p["ybot"] - Y)
        c.lampf *= 1.0 - 0.5 * np.exp(-((np.maximum(dxs, 0.0) / 3.2) ** 2)) * (dxs > -0.5) * rows_in
        sl = c.timber(p["x"] - p["pw"] / 2, p["ytop"], p["x"] + p["pw"] / 2, p["ybot"], timber, 0.30, 0.9, "y", r, k=p["k"])
        c.timber(p["x"] - p["cw"] / 2, p["ytop"] - p["ch"], p["x"] + p["cw"] / 2, p["ytop"], timber, 0.32, 0.9, "x", r)
        if sl is not None:
            # round timber: the side toward the lamp catches it, the other falls off; darker under the cap and in the muck at its foot
            u = ((X[:, sl[1]] - p["x"]) / (p["pw"] / 2)) * away  # -1 lamp side .. +1 far side
            c.lampf[sl] *= np.clip(1.08 - 0.42 * u - 0.1 * u * u, 0.3, 1.3)
            yy = Y[sl[0]]
            c.lampf[sl] *= (1.0 - 0.45 * sm(p["ytop"] + 5.0, p["ytop"], yy)) * (1.0 - 0.4 * sm(p["ybot"] - 5.0, p["ybot"], yy))
            c.alb[sl] *= (1.0 - 0.3 * sm(p["ybot"] - 4.0, p["ybot"], yy))[..., None]
    yfw = float(st["y"])
    c.timber(XL - 12, g["capy"], XR + 12, g["capy"] + 7.2, timber, 0.5, 1.0, "x", r)
    c.timber(XL - 16, yfw - 4.2, XR + 16, yfw + 1.0, timber * 0.92, 0.5, 1.0, "x", r)
    # the lamp: a lantern on a wire from a nail in the roof (tin cap, glass, tin foot)
