    jag = np.interp(Y[:, 0], rows1, g["jag"]).astype(np.float32) + 0.5 * noise1d(h, 2.0 * S, fine)
    dl = np.maximum(0.0, np.maximum(XL - X, X - XR))
    length = np.where(X < SHAFT_X, g["length"][0], g["length"][1]).astype(np.float32)
    e = 0.26
