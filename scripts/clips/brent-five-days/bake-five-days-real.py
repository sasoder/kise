def rock_band(h, w, rock_src, r, lo=9.0, amount=1.0):
    """The rock photos at THIS scale, only their structure finer than `lo` px, as a factor around 1:
    what an enlarged plate lacks, from the same walls."""
    tex = dts.collage(h, w, rock_src, r).mean(2)
    band = tex / np.maximum(gauss_big(tex, lo), 0.05)
    return (1.0 + amount * np.clip(band - 1.0, -0.45, 0.6)).astype(np.float32)


def resharpen(a, sigma, k):
    """Unsharp mask: takes back most of the enlarged plate's own blur."""
    return np.maximum(a + k * (a - gauss(a, sigma)), 0.0)


# ---------------------------------------------------------------- a canvas at scale S
class Hi:
    """Reflectance + three light factors over the world box (x0, wy0)-(x1, wy1) at scale S: amb (the sky and our
    own lamp), lampf (a station's lamp), hl (the man's headlamp). Coordinates given to rect() are the 1x canvas's
    edge coordinates (world y, not canvas rows)."""

    def __init__(self, x0, wy0, x1, wy1, S):
        self.x0, self.wy0, self.S = x0, wy0, S
        self.w, self.h = int(round((x1 - x0) * S)), int(round((wy1 - wy0) * S))
        self.alb = np.zeros((self.h, self.w, 3), np.float32)
        self.amb = np.zeros((self.h, self.w), np.float32)
        self.lampf = np.zeros((self.h, self.w), np.float32)
        self.hl = np.zeros((self.h, self.w), np.float32)
        self.cov = np.zeros((self.h, self.w), np.float32)
        # the 1x pixel-index coordinate of every column and row (pixel i of the 1x canvas is at i)
        self.X = (x0 + (np.arange(self.w, dtype=np.float32) + 0.5) / S - 0.5)[None, :]
        self.Y = (wy0 + (np.arange(self.h, dtype=np.float32) + 0.5) / S - 0.5)[:, None]

    def rect(self, x0, y0, x1, y1, alb, amb=None, lampf=None, a=1.0, tone_=None, hl=None):
        S = self.S
        x0, x1 = (x0 - self.x0) * S, (x1 - self.x0) * S
        y0, y1 = (y0 - self.wy0) * S, (y1 - self.wy0) * S
        ix0, iy0 = int(math.floor(x0)), int(math.floor(y0))
        ix1, iy1 = int(math.ceil(x1)), int(math.ceil(y1))
        ix0c, iy0c, ix1c, iy1c = max(ix0, 0), max(iy0, 0), min(ix1, self.w), min(iy1, self.h)
        if ix1c <= ix0c or iy1c <= iy0c:
            return None
        xs = np.arange(ix0c, ix1c, dtype=np.float32)
        ys = np.arange(iy0c, iy1c, dtype=np.float32)
        cx = np.clip(np.minimum(xs + 1, x1) - np.maximum(xs, x0), 0, 1)
        cy = np.clip(np.minimum(ys + 1, y1) - np.maximum(ys, y0), 0, 1)
        cov = (np.outer(cy, cx) * a).astype(np.float32)
        sl = (slice(iy0c, iy1c), slice(ix0c, ix1c))
        col = np.asarray(alb, np.float32)
        if tone_ is not None:
            th, tw = cov.shape
            ty, tx = iy0c - iy0, ix0c - ix0  # the piece of the timber's grain that is inside the box
            tone_ = np.pad(tone_, ((0, max(0, ty + th - tone_.shape[0])), (0, max(0, tx + tw - tone_.shape[1]))), mode="edge")[ty : ty + th, tx : tx + tw]
            col = col[None, None, :] * tone_[..., None]
        self.alb[sl] = self.alb[sl] * (1 - cov[..., None]) + col * cov[..., None]
        for arr, v in ((self.amb, amb), (self.lampf, lampf), (self.hl, hl)):
            if v is not None:
                arr[sl] = arr[sl] * (1 - cov) + v * cov
        self.cov[sl] = np.maximum(self.cov[sl], cov)
        return sl

    def timber(self, x0, y0, x1, y1, alb, amb, lampf, along, r, k=1.0, lit_edge=None, hl=None):
        """A timber with grain cut from the timber photos at this scale."""
        S = self.S
        hh = int(math.ceil(y1 * S) - math.floor(y0 * S)) + 1
        ww = int(math.ceil(x1 * S) - math.floor(x0 * S)) + 1
        t = dts.wood_tone(hh, ww, r, along) * k
        e = max(1, int(round(S * 0.9)))
        if lit_edge == "right":
            t[:, -e - 1 :] *= 1.22
        elif lit_edge == "left":
            t[:, : e + 1] *= 1.22
        return self.rect(x0, y0, x1, y1, alb, amb=amb, lampf=lampf, tone_=t, hl=hl)


# ---------------------------------------------------------------- the plate's shaft
def set_rows(P):
    """World y of the shaft's timber sets, read off the plate (the bearers at both walls), gaps filled."""
    L = P.mean(2)
    prof = 0.5 * (L[:, XL + 6 : XL + 12].mean(1) + L[:, XR - 12 : XR - 6].mean(1))
    hp = prof - gauss(prof[None, :], 12.0)[0]
    rows, i = [], 1
    while i < len(hp) - 1:
        if hp[i] > 0.035 and hp[i] >= hp[i - 1] and hp[i] >= hp[i + 1]:
            rows.append(i + PLATE_Y0 + 0.5)
            i += 20
        else:
            i += 1
    first = rows[0]
    while first - 60.0 > COLLAR_Y + 20:  # the first sets lie under the cap, above the plate's first row
        first -= 60.0
        rows.insert(0, first)
    out = [rows[0]]
    for y in rows[1:]:
        gap = y - out[-1]
        n = int(round(gap / 62.0))
        for k in range(1, n):
            out.append(out[-1] + gap / n)
        out.append(y)
    return out


def station_rows():
    return [(s["y"] - s["room"] - 12, s["y"] + 4) for s in dts.STATIONS]


def synth_shaft(x0, wy0, x1, wy1, S, sets, r, timber, lagging):
    """The shaft's timbering re-drawn at scale S on the plate's own set rows, with the plate's light factors
    (amb: sky and our lamp, lampf: a station lamp) and one more (hl: the man's headlamp).
    Returns (canvas, alpha): alpha is 0 outside the timbered opening. About one wall timber in five is pale
    new wood and the lagging changes tone board by board: under the fall's blur those are the dashes of light
    that go past him (irregular, so they cannot strobe against the frame rate the way the evenly spaced sets would)."""
    c = Hi(x0, wy0, x1, wy1, S)
    h, w = c.h, c.w
    X, Y = c.X, c.Y
    prof = np.maximum(np.sin(np.pi * np.clip((X - XL) / (XR - XL), 0, 1)), 0) ** 0.7
    sky = np.exp(-np.maximum(Y, 0) / 95.0)
    # the far wall: vertical lagging boards
    lag = np.ones((h, w), np.float32)
    edges = [XL + 6.0]
    while edges[-1] < XR - 6:
        edges.append(edges[-1] + float(r.uniform(8, 13)))
    SEG = 300.0
    nseg = int((wy1 - wy0) // SEG + 3)
    for a, b in zip(edges[:-1], edges[1:]):
        seg = 0.62 + 0.78 * r.random(nseg).astype(np.float32)
        seg_y = np.clip((Y[:, 0] - wy0) / SEG + float(r.uniform(0, 1)), 0, nseg - 1.001)
        i0 = np.floor(seg_y).astype(np.int64)
        t = sm(0.0, 0.03, seg_y - i0)  # the board is butt-jointed: a quick step in tone
        col = seg[np.maximum(i0 - 1, 0)] * (1 - t) + seg[i0] * t
        inb = (sm(-0.5, 0.5, (X - a) * S) * sm(-0.5, 0.5, (b - X) * S))[0]
        lag = lag * (1 - inb[None, :]) + col[:, None] * inb[None, :]
        gapm = np.exp(-0.5 * (((X - a) * S) / max(0.55, 0.42 * S)) ** 2)
        lag *= 1.0 - 0.6 * gapm
    lag *= 1.0 + 0.12 * vnoise(h, w, 2.0 * S, 40 * S, r) + 0.07 * vnoise(h, w, 1.0, 16 * S, r) + 0.03 * vnoise(h, w, 1.2, 2.0, r)
    inside = sm(-0.6, 0.6, (X - (XL - 1.0)) * S) * sm(-0.6, 0.6, ((XR + 1.0) - X) * S)
    c.alb[:] = lagging[None, None, :] * lag[..., None]
    c.amb[:] = (0.15 + 0.60 * sky) * (0.22 + 0.78 * prof)
    c.lampf[:] = 0.55 * (0.35 + 0.65 * prof)
    c.hl[:] = 0.78 * (0.5 + 0.5 * prof)
    # far corners: two posts and a guide timber (they take the far wall's light)
    for fx, fw in ((XL + 7.5, 4.2), (XR - 11.7, 4.2), (SHAFT_X + 11.0, 3.4)):
        c.timber(fx, wy0, fx + fw, wy1, lagging * 1.5, None, None, "y", r)
    stn = station_rows()

    def clear(y):
        return all(not (a - 6 <= y <= b + 6) for a, b in stn)

    prev = COLLAR_Y + 2
    for ys in sets + [sets[-1] + 60]:
        if ys < wy0 - 80 or prev > wy1 + 80:
            prev = ys
            continue
        for side in (-1, 1):
            pw = float(r.uniform(4.8, 6.2))
            jog = float(r.uniform(-0.6, 0.6))
            kt = float(r.uniform(1.3, 1.6)) if r.random() < 0.24 else float(r.uniform(0.62, 1.0))
            xa = (XL + jog) if side < 0 else (XR - pw + jog)
            if ys - prev > 8:
                c.timber(xa, prev + 3.0, xa + pw, ys - 2.0, timber, 1.12, 1.0, "y", r, k=kt, lit_edge="right" if side < 0 else "left", hl=0.74)
        prev = ys
        if not clear(ys):
            continue
        bh = float(r.uniform(5.6, 7.2))
        ksky = 0.15 + 0.40 * math.exp(-max(ys, 0.0) / 95.0)
        sl = c.timber(XL + 6, ys - bh / 2, XR - 6, ys + bh / 2, lagging * 1.25, ksky, 0.38, "x", r, k=float(r.uniform(0.8, 1.15)), hl=0.5)
        if sl is not None:  # the plate's own shadow under the end plate
            a_, b_ = sl[0].stop, min(h, sl[0].stop + int(round(3 * S)))
            xa_, xb_ = max(0, int((XL + 6 - x0) * S)), min(w, int((XR - 6 - x0) * S))
            c.amb[a_:b_, xa_:xb_] *= 0.7
            c.hl[a_:b_, xa_:xb_] *= 0.7
        for side in (-1, 1):
            ln = float(r.uniform(8, 15))
            th = float(r.uniform(5.6, 7.4))
            yo = float(r.uniform(-1.8, 1.8))
            xa = XL + 5 if side < 0 else XR - 5 - ln
            kb = float(r.uniform(1.35, 1.75)) if r.random() < 0.3 else float(r.uniform(0.55, 1.05))
            c.timber(xa, ys + yo - th / 2, xa + ln, ys + yo + th / 2, timber, 0.50, 0.55, "x", r, k=kb, hl=0.72)
    return c, inside * np.ones((h, 1), np.float32)


def head_lit(c, amb_rows):
    """The timbering under his headlamp (plus half of what it gets anyway), linear."""
    return c.alb * (HEAD[None, None, :] * c.hl[..., None] + 0.5 * amb_rows[:, None, :] * c.amb[..., None])


# ---------------------------------------------------------------- the station, call for call
def station_stream(st):
    """bake-down-the-shaft.py's station(): the same random stream, so the same roof, floor, heading and posts."""
    yf = st["y"] + TOP
    h, room = st["h"], st["room"]
    r_ = np.random.default_rng(int(st["y"]) * 13 + 5)
    cols_ = np.arange(max(0, XL - st["left"] - 16), min(W, XR + st["right"] + 16))
    n = len(cols_)
    xf = cols_.astype(np.float32)
    dl = np.maximum(0.0, np.maximum(XL - xf, xf - XR))
    length = np.where(xf < SHAFT_X, float(st["left"]), float(st["right"])).astype(np.float32)
    near = 1.0 - sm(35.0, 150.0, dl)
    hh = h + (room - h) * near
    close = sm(length - 34.0, length + 2.0, dl) ** 1.6
    rough = sm(18.0, 110.0, dl)
    roof = yf - hh * (1 - 0.40 * close) + 3.0 * noise1d(n, 44, r_) + 1.6 * noise1d(n, 12, r_)
    floor = yf - hh * 0.10 * close + rough * (2.0 * noise1d(n, 60, r_) + 1.0 * noise1d(n, 8, r_))
    r0, r1 = int(yf - room - 30), int(yf + 12)
    nr = r1 - r0
    jag = 2.5 * noise1d(nr, 9, r_) + 4.0 * noise1d(nr, 30, r_)
    so = int(r_.integers(0, 240 - nr))
    sx = int(r_.integers(0, W - n + 1))
    flip = bool(r_.random() < 0.5)
    muck = vnoise(nr, n, 4, 2.5, r_)

    def col_at(x):
        return int(np.clip(round(x) - int(cols_[0]), 0, n - 1))

    lx = (XR + st["lamp_dx"]) if st["lamp"] > 0 else (XL - st["lamp_dx"])
    posts = []
    for side, ln in ((-1, st["left"]), (1, st["right"])):
        x = 40.0 + float(r_.uniform(0, 14))
        while x < ln - 30:
            cxp = (XL - x) if side < 0 else (XR + x)
            if abs(cxp - lx) < 26:
                x += 30.0
                continue
            ci = col_at(cxp)
            pw = float(r_.uniform(4.2, 5.6))
            ytop, ybot = roof[ci] + 6.5, floor[ci] - 0.5
            hh_, ww_ = int(math.ceil(ybot) - math.floor(ytop)), int(math.ceil(cxp + pw / 2) - math.floor(cxp - pw / 2))
            if hh_ > 12:
                dts.wood_tone(hh_, ww_, r_, "y")
                k = float(r_.uniform(0.8, 1.05))
                cw, ch = float(r_.uniform(8, 10.5)), float(r_.uniform(6, 7.5))
                dts.wood_tone(int(math.ceil(ytop) - math.floor(ytop - ch)), int(math.ceil(cxp + cw / 2) - math.floor(cxp - cw / 2)), r_, "x")
                posts.append(dict(x=cxp, pw=pw, ytop=ytop - TOP, ybot=ybot - TOP, k=k, cw=cw, ch=ch))
            x += float(r_.uniform(58, 78))
    capy = roof[col_at(SHAFT_X)] + 3.0 - TOP
    lamp = (float(lx), float(roof[col_at(lx)] + 15.0) - TOP)
    return dict(cols=cols_, roof=roof - TOP, floor=floor - TOP, r0=r0 - TOP, nr=nr, jag=jag, so=so, sx=sx, flip=flip, muck=muck, posts=posts, capy=capy, lamp=lamp, length=(float(st["left"]), float(st["right"])))


def lamp_fall(X, Y, lamp, r, k):
    d2 = (X - lamp[0]) ** 2 + ((Y - lamp[1]) * 1.15) ** 2
    R = r * 8
    return (k / (1.0 + d2 / (r * r)) * sm(R, R * 0.55, np.sqrt(d2))).astype(np.float32), d2


LEVEL_KEEP = 0.2  # how much of a passed level's lamp light stays on its rock


def level_box(st):
    return max(0, XL - st["left"] - 40), st["y"] - st["room"] - 50, min(W, XR + st["right"] + 40), st["y"] + 24


def unlight_level(P, st):
    """A level he passes on the way down, with its lamp's light taken off the rock (LEVEL_KEEP of it stays):
    the component draws the lamp itself as one clean streak. In place, on the 1x plate; returns the box."""
    g = station_stream(st)
    x0, wy0, x1, wy1 = level_box(st)
    X = np.arange(x0, x1, dtype=np.float32)[None, :]
    Y = np.arange(wy0, wy1, dtype=np.float32)[:, None]
    cols = g["cols"].astype(np.float32)
    roof = np.interp(X[0], cols, g["roof"]).astype(np.float32)
    floor = np.interp(X[0], cols, g["floor"]).astype(np.float32)
    rows1 = g["r0"] + np.arange(g["nr"], dtype=np.float32)
    jag = np.interp(Y[:, 0], rows1, g["jag"]).astype(np.float32)
    dl = np.maximum(0.0, np.maximum(XL - X, X - XR))
    length = np.where(X < SHAFT_X, g["length"][0], g["length"][1]).astype(np.float32)
    m = sm(-0.8, 0.8, Y - roof[None, :]) * sm(-0.8, 0.8, floor[None, :] - Y) * sm(1.0, -1.0, dl - (length + jag[:, None]))
    m[(Y[:, 0] < g["r0"]) | (Y[:, 0] > g["r0"] + g["nr"])] = 0.0
    v = np.clip((Y - roof[None, :]) / np.maximum(floor - roof, 1)[None, :], 0, 1)
    ao = 0.5 + 0.5 * np.maximum(np.sin(np.pi * v), 0) ** 0.5
    far = 1.0 - 0.6 * sm(0.15, 1.0, dl / length)
    prox = gauss(m, 11.0) * (1 - m)
    prof = np.maximum(np.sin(np.pi * np.clip((X - XL) / (XR - XL), 0, 1)), 0) ** 0.7
    in_shaft = (sm(-1.0, 1.0, X - (XL - 0.6)) * sm(-1.0, 1.0, (XR + 0.6) - X)) * np.ones_like(Y)
    wall = np.maximum(sm(1.0, -1.0, X - (XL + 6.2)), sm(1.0, -1.0, (XR - 6.2) - X))
    amb = (1 - in_shaft) + in_shaft * (wall * 1.12 + (1 - wall) * 0.15 * (0.22 + 0.78 * prof))
    lampf = (1 - in_shaft) * 0.5 * prox + in_shaft * (wall * 1.0 + (1 - wall) * 0.55 * (0.35 + 0.65 * prof))
    amb = amb * (1 - m) + 0.21 * far * ao * m
    lampf = lampf * (1 - m) + ao * m
    L, d2 = lamp_fall(X, Y, g["lamp"], st["lamp_r"], st["lamp_k"])
    emit = (np.exp(-d2 / (2 * 2.1**2))[..., None] * np.array([1.0, 0.86, 0.60], np.float32) + (0.20 * np.exp(-np.sqrt(d2) / 16.0))[..., None] * np.array([0.85, 0.50, 0.20], np.float32)) * st["lamp_k"]
    A = ambient(Y[:, 0])[:, None, :]
    lit = WARM[None, None, :] * (L * lampf)[..., None]
    sl = (slice(wy0 - PLATE_Y0, wy1 - PLATE_Y0), slice(x0, x1))
    V = np.maximum(untone(P[sl]) - gauss(emit, 1.15) * (1 - LEVEL_KEEP), 0.0)
    P[sl] = tone(V * (A * amb[..., None] + LEVEL_KEEP * lit) / (A * amb[..., None] + lit))
    return x0, wy0, x1, wy1


def rock_detail(h, w, rock_src, det_src, r, fine, band, mid, coarse=0.0):
    """What an enlarged plate lacks, from the same walls, as one factor around 1: the photos' fine grain,
    their structure finer than ~9 px at this scale, the same again from the photos at twice the size, and
    (for the 5x plate) once more at four times."""
    det = dts.collage(h, w, det_src, r, tile=520, step=400, blob=(560,), blob_step=(340,), skip=(0.0,), scale_range=(0.85, 1.15)).mean(2)
    out = 1.0 + fine * (gauss(det, 0.7) - 1.0)
    del det
    out *= rock_band(h, w, rock_src, r, 9.0, band)
    if mid > 0:
        tex = dts.collage(h, w, rock_src, r, scale_range=(1.9, 2.6)).mean(2)
        out *= 1.0 + mid * np.clip(tex / np.maximum(gauss_big(tex, 22.0), 0.05) - 1.0, -0.45, 0.6)
    if coarse > 0:
        tex = dts.collage(h, w, rock_src, r, scale_range=(3.5, 4.5)).mean(2)
        out *= 1.0 + coarse * np.clip(tex / np.maximum(gauss_big(tex, 44.0), 0.05) - 1.0, -0.45, 0.6)
    return out.astype(np.float32)


def bake_station(P, det_src, rock_src, sets, timber, lagging, check):
    S = 5.0
    X0, X1, WY0, WY1 = 300, 740, 6560, 7380
    ON0, ON1 = 6700, 7300
