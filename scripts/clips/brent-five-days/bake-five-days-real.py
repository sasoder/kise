# ---------------------------------------------------------------- tone
def tone(o):
    o = np.maximum(o, 0)
    hi = np.maximum(o - 0.6, 0)
    o = np.minimum(o, 0.6) + 0.4 * (1.0 - np.exp(-hi / 0.4))
    return BLACK + (1.0 - BLACK) * o


def untone(v):
    o = np.clip((v - BLACK) / (1.0 - BLACK), 0.0, 0.985)
    hi = np.clip((o - 0.6) / 0.4, 0.0, 0.96)
    return np.where(o > 0.6, 0.6 - 0.4 * np.log(1.0 - hi), o).astype(np.float32)


def ambient(wy):
    """The light on the cut face at world y (rows x 3), as bake-down-the-shaft.py has it."""
    wy = np.asarray(wy, np.float32)
    dusk_w = 1.0 - sm(0.0, 1500.0, wy)
    lamp_w = sm(150.0, 1500.0, wy)
    hue_w = sm(300.0, 3000.0, wy)
    lamp_col = (DUSK * (float(LAMP.mean()) / float(DUSK.mean())))[None, :] * (1 - hue_w)[:, None] + LAMP[None, :] * hue_w[:, None]
    return DUSK[None, :] * dusk_w[:, None] + lamp_col * lamp_w[:, None]


def upscale(a, S):
    """Bicubic enlargement by S; the size times S must be whole."""
    h, w = a.shape[:2]
    hh, ww = h * S, w * S
    assert abs(hh - round(hh)) < 1e-6 and abs(ww - round(ww)) < 1e-6, (h, w, S)
    hh, ww = int(round(hh)), int(round(ww))
    if a.ndim == 2:
        return resize_f(a, ww, hh)
    return np.dstack([resize_f(a[..., k], ww, hh) for k in range(a.shape[2])])


