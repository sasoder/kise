// The "points and lines" for PointsAndLines (sarah-insurgency, cut 12; reused by cut 40 HornsOfTheDilemma): what
// Japan really held in North and East China by 1939-40, the cities and the railways (+ the Yangtze to Wuhan), as
// geometry on the clip's CHINA world (insChinaMapData.ts, world px ~ km).
//
//   bun scripts/clips/sarah-insurgency/bake-points-and-lines.mjs
//
// Writes generated/components/sarah-insurgency/pointsAndLinesData.ts:
//   HELD_LINES  the held railway sections (RAIL_HELD: from station to station on each RAIL_*), and the Yangtze from
//               Wuhan to its mouth, as polylines (world px), each with its kind (rail | river)
//   HELD_CITIES the garrisoned towns (PLACES keys)
//   BANDS       ONE region (MapGround3D territory d, land-clipped to OCCUPIED_1939): a thin band (BAND_HALF each
//               side) along every held line, and a disc (CITY_R) at every held city: the cream hold that is left
//               once the guerrillas own the land between.
// Railway courses are the world data's own (city-to-city, APPROXIMATE); the held list is COMMON.md's.
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import polygonClipping from "polygon-clipping";
import * as C from "../../../generated/components/sarah-insurgency/insChinaMapData.ts";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const BAND_HALF = 11;
const CITY_R = 30;
const STEP = 6;
const HELD_CITIES = ["beiping", "tianjin", "baoding", "shijiazhuang", "taiyuan", "jinan", "qingdao", "xuzhou", "kaifeng", "xinxiang", "nanjing", "shanghai", "hangzhou", "wuhan"];

const RAILS = { pinghan: C.RAIL_PINGHAN, jinpu: C.RAIL_JINPU, zhengtai: C.RAIL_ZHENGTAI, jiaoji: C.RAIL_JIAOJI, longhai: C.RAIL_LONGHAI, huning: C.RAIL_HUNING, huhang: C.RAIL_HUHANG, beining: C.RAIL_BEINING };
const cumul = (pts) => pts.reduce((a, p, i) => (a.push(i ? a[i - 1] + Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]) : 0), a), []);
/** the part of a route between arclengths s0 and s1, resampled every STEP */
const section = (route, s0, s1) => {
  const cs = cumul(route.pts);
  const scale = cs[cs.length - 1] / route.len; // the stations' arclengths are on the same polyline
  const at = (s) => {
    const S = s * scale;
    let i = 1;
    while (i < cs.length - 1 && cs[i] < S) i++;
    const q = (S - cs[i - 1]) / Math.max(1e-9, cs[i] - cs[i - 1]);
    const a = route.pts[i - 1];
    const b = route.pts[i];
    return [a[0] + (b[0] - a[0]) * q, a[1] + (b[1] - a[1]) * q];
  };
  const n = Math.max(2, Math.ceil(Math.abs(s1 - s0) / STEP));
  const out = [];
  for (let k = 0; k <= n; k++) out.push(at(s0 + ((s1 - s0) * k) / n).map((v) => Math.round(v * 100) / 100));
  return out;
};
const lines = [];
for (const [rail, a, b] of C.RAIL_HELD) {
  const r = RAILS[rail];
  const s0 = r.stations[a];
  const s1 = r.stations[b];
  if (s0 === undefined || s1 === undefined) throw new Error(`no station ${a} / ${b} on ${rail}`);
  lines.push({ key: `${rail}:${a}-${b}`, kind: "rail", from: a, to: b, pts: section(r, s0, s1) });
}
const Y = C.RIVER_YANGTZE;
lines.push({ key: "yangtze:wuhan-mouth", kind: "river", from: "wuhan", to: "mouth", pts: section(Y, Y.stations.wuhan, Y.stations.mouth) });

const circle = (c, r, n = 16) => {
  const ring = [];
  for (let i = 0; i < n; i++) ring.push([c[0] + r * Math.cos((i / n) * 2 * Math.PI), c[1] + r * Math.sin((i / n) * 2 * Math.PI)]);
  ring.push(ring[0]);
  return [ring];
};
const polys = [];
for (const L of lines) {
  const p = L.pts;
  for (let i = 1; i < p.length; i++) {
    const [a, b] = [p[i - 1], p[i]];
    const l = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
    const n = [(-(b[1] - a[1]) / l) * BAND_HALF, ((b[0] - a[0]) / l) * BAND_HALF];
    polys.push([[[a[0] + n[0], a[1] + n[1]], [b[0] + n[0], b[1] + n[1]], [b[0] - n[0], b[1] - n[1]], [a[0] - n[0], a[1] - n[1]], [a[0] + n[0], a[1] + n[1]]]]);
    polys.push(circle(b, BAND_HALF, 10));
  }
  polys.push(circle(p[0], BAND_HALF, 10));
}
for (const k of HELD_CITIES) polys.push(circle(C.PLACES[k], CITY_R, 28));
let u = polygonClipping.union(...polys);
u = polygonClipping.intersection(u, C.OCCUPIED_POLY);
const r1 = (v) => Math.round(v * 10) / 10;
const d = u.map((poly) => poly.map((ring) => `M${ring.slice(0, -1).map((q) => `${r1(q[0])},${r1(q[1])}`).join("L")}Z`).join("")).join("");
let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
for (const poly of u) for (const ring of poly) for (const [x, y] of ring) { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); }

const out = `// Generated by scripts/clips/sarah-insurgency/bake-points-and-lines.mjs - do not edit by hand.
// What Japan really held in North / East China by 1939-40 ("points and lines"), on the CHINA world (world px).
// Railway courses are the world data's own (city-to-city, APPROXIMATE); the held sections are COMMON.md's list.
import type { P2 } from "./insChinaMapData";
export type HeldLine = { key: string; kind: "rail" | "river"; from: string; to: string; pts: P2[] };
/** the held railway sections and the Yangtze from Wuhan to the mouth */
export const HELD_LINES: HeldLine[] = ${JSON.stringify(lines)};
/** the garrisoned towns (keys of PLACES) */
export const HELD_CITIES = ${JSON.stringify(HELD_CITIES)} as const;
/** the band half-width along the lines and the radius at the towns (world px) */
export const BAND_HALF = ${BAND_HALF};
export const CITY_R = ${CITY_R};
/** THE HOLD THAT IS LEFT: bands along the held lines + discs at the towns, clipped to OCCUPIED_1939 (a territory d) */
export const BANDS = { d: ${JSON.stringify(d)}, box: [${r1(x0)}, ${r1(y0)}, ${r1(x1)}, ${r1(y1)}] as [number, number, number, number] };
`;
const file = join(REPO, "generated/components/sarah-insurgency/pointsAndLinesData.ts");
writeFileSync(file, out);
console.log(`wrote ${file}: ${lines.length} lines, ${u.length} polygons, d ${d.length} chars, box ${[x0, y0, x1, y1].map(r1)}`);
