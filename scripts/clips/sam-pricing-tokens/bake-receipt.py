# Bake the receipt cut-outs for cut 17 WhatAmIPayingFor (sam-pricing-tokens).
# Source: assets-src/sam-pricing-tokens/receipt_thermal_long_fuelstation_scan_PD.jpg (Wikimedia Commons, public domain;
# images/cutout_sources/SOURCES.md item 2): a flatbed scan of a real thermal till receipt, white paper edge to edge.
# Writes (public/sam-pricing-tokens/ for reference, inlined into generated/components/sam-pricing-tokens/receiptData.ts):
#   receipt_paper.jpg   the paper with ALL of its print removed (a morphological closing lifts the dark print into
#                       the paper; the scan's paper is near-white edge to edge, so this is the blank thermal paper)
#   receipt_rule.png    the scan's own dotted rule (real thermal print), alpha from darkness, the ink kept
#   receipt_total.png   the scan's own printed word "TOTAL" (real thermal print), alpha from darkness
# The cut draws the outline (torn zig-zag foot), the blank "?" rows and the amber sticker on top.
# Run with the system python and the user's site-packages (no installs):
#   /usr/bin/python3 -I scripts/clips/sam-pricing-tokens/bake-receipt.py
import base64
import io
import os
import sys

sys.path.append("/Users/tom/Library/Python/3.9/lib/python/site-packages")
import numpy as np  # noqa: E402
from PIL import Image, ImageFilter  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SRC = os.path.join(ROOT, "assets-src/sam-pricing-tokens/receipt_thermal_long_fuelstation_scan_PD.jpg")
PUB = os.path.join(ROOT, "public/sam-pricing-tokens")
DATA = os.path.join(ROOT, "generated/components/sam-pricing-tokens/receiptData.ts")
os.makedirs(PUB, exist_ok=True)

im = Image.open(SRC).convert("RGB")
W, H = im.size  # 1280 x 4006

# --- the blank paper: a strip of the receipt's length-to-width ratio (312 x 800 world), all print closed away
PAPER_ASPECT = 312 / 800
ph = int(W / PAPER_ASPECT)
y0 = (H - ph) // 2
strip = im.crop((0, y0, W, y0 + ph))
closed = strip.filter(ImageFilter.MaxFilter(25)).filter(ImageFilter.MaxFilter(25)).filter(ImageFilter.MinFilter(9)).filter(ImageFilter.GaussianBlur(3))
paper = closed.resize((624, 1600), Image.LANCZOS)
pa = np.asarray(paper).astype(float)
assert pa.mean(2).min() > 200, "print left on the paper"
paper.save(os.path.join(PUB, "receipt_paper.jpg"), quality=90)


def print_cutout(box, name, lo=70, hi=228, pad=6):
    """real thermal print: the ink's darkness becomes alpha; the ink's own tone is kept (the grade maps it)."""
    c = im.crop(box).convert("L")
    g = np.asarray(c).astype(float)
    a = np.clip((hi - g) / (hi - lo), 0, 1)
    ys, xs = np.where(a > 0.25)
    y_0, y_1, x_0, x_1 = max(0, ys.min() - pad), min(g.shape[0], ys.max() + pad), max(0, xs.min() - pad), min(g.shape[1], xs.max() + pad)
    a = a[y_0:y_1, x_0:x_1]
    ink = np.clip(g[y_0:y_1, x_0:x_1], 0, 120)
    rgba = np.dstack([ink, ink, ink, a * 255]).astype(np.uint8)
    out = Image.fromarray(rgba, "RGBA")
    out.save(os.path.join(PUB, name))
    return out


rule = print_cutout((30, 1982, 1225, 2006), "receipt_rule.png")
total = print_cutout((80, 2270, 400, 2405), "receipt_total.png")


def data_url(path, mime):
    with open(path, "rb") as fh:
        return f"data:{mime};base64," + base64.b64encode(fh.read()).decode("ascii")


with open(DATA, "w") as fh:
    fh.write(
        "// receiptData — cut 17's baked receipt cut-outs, inlined as data URLs (CRAFT \"Bitmaps inside an SVG\").\n"
        "// GENERATED by scripts/clips/sam-pricing-tokens/bake-receipt.py from\n"
        "// assets-src/sam-pricing-tokens/receipt_thermal_long_fuelstation_scan_PD.jpg (Wikimedia Commons\n"
        "// \"File:Tankquittung_HIT-Tankstelle_Rheinbach_mit_Abschnitt_Technische_Sicherheitseinrichtung,_2020.jpg\",\n"
        "// public domain): the paper with all print removed, and its own printed dotted rule and word TOTAL. Do not edit.\n"
    )
    fh.write(f"export const RECEIPT_PAPER = {{ src: \"{data_url(os.path.join(PUB, 'receipt_paper.jpg'), 'image/jpeg')}\", aspect: {624 / 1600:.6f} }};\n")
    fh.write(f"export const RECEIPT_RULE = {{ src: \"{data_url(os.path.join(PUB, 'receipt_rule.png'), 'image/png')}\", aspect: {rule.width / rule.height:.6f} }};\n")
    fh.write(f"export const RECEIPT_TOTAL = {{ src: \"{data_url(os.path.join(PUB, 'receipt_total.png'), 'image/png')}\", aspect: {total.width / total.height:.6f} }};\n")
print("paper", paper.size, "rule", rule.size, "total", total.size, "->", DATA)
