# Bake the "3 nm" chip for cut 48 NanometersVsReality (sam-pricing-tokens).
# Source: assets-src/sam-pricing-tokens/die_LunarLake_TSMC-N3B_computetile_poly_ext.jpg (Fritzchens Fritz, CC0, Commons
# "Intel@TSMC_N3_N6@LunarLake@LNL(4P+4LPE)@CoreUltra200Series@DSCx06_poly@5xExt", the 3840 px thumbnail): an optical
# die shot of Intel Lunar Lake; the big upper die is the Compute Tile, made on TSMC N3B (a real "3 nm" chip).
# The Compute Tile is a clean rectangle, so the cut-out is a crop (no matte): source px (57, 58) - (3782, 2018),
# measured from the row / column luminance profiles (the black gap around it is < 4 / 255).
# Writes (RGB JPEG, the tile is opaque and rectangular):
#   public/sam-pricing-tokens/chip_computetile.jpg        the sharp tile, 2800 px wide (the dive's f0 .. k ~4)
#   public/sam-pricing-tokens/chip_computetile_soft.jpg   the same tile defocused (Gaussian sigma 6 px at 2800 w),
#                                                         stored at 1400 w: what the photo still shows past its
#                                                         resolution (the dive crossfades sharp -> soft = a focus pull)
#   generated/components/sam-pricing-tokens/nanometersData.ts   both as data: URLs + the aspect (CRAFT "Bitmaps inside
#                                                         an SVG")
# Run (system python + the user's site-packages, no installs):
#   /usr/bin/python3 -I scripts/clips/sam-pricing-tokens/bake-chip.py <repo root>
import base64
import io
import sys

sys.path.append("/Users/tom/Library/Python/3.9/lib/python/site-packages")
from PIL import Image, ImageFilter  # noqa: E402

ROOT = sys.argv[1]
SRC = f"{ROOT}/assets-src/sam-pricing-tokens/die_LunarLake_TSMC-N3B_computetile_poly_ext.jpg"
OUT_SHARP = f"{ROOT}/public/sam-pricing-tokens/chip_computetile.jpg"
OUT_SOFT = f"{ROOT}/public/sam-pricing-tokens/chip_computetile_soft.jpg"
OUT_TS = f"{ROOT}/generated/components/sam-pricing-tokens/nanometersData.ts"
CROP = (57, 58, 3782, 2018)
W = 2800
SOFT_SIGMA = 6
SOFT_W = 1400

tile = Image.open(SRC).convert("RGB").crop(CROP)
H = round(W * tile.height / tile.width)
sharp = tile.resize((W, H), Image.LANCZOS)
soft = sharp.filter(ImageFilter.GaussianBlur(SOFT_SIGMA)).resize((SOFT_W, round(SOFT_W * H / W)), Image.LANCZOS)


def jpg(im: Image.Image, path: str, q: int) -> bytes:
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=q, optimize=True, progressive=False)
    data = buf.getvalue()
    with open(path, "wb") as f:
        f.write(data)
    return data


a = jpg(sharp, OUT_SHARP, 86)
b = jpg(soft, OUT_SOFT, 86)
aspect = W / H
with open(OUT_TS, "w") as f:
    f.write(
        "// GENERATED by scripts/clips/sam-pricing-tokens/bake-chip.py — do not edit.\n"
        "// The Intel Lunar Lake Compute Tile (TSMC N3B), optical die shot, poly layer, Fritzchens Fritz, CC0 (Wikimedia\n"
        "// Commons). Crop of source px (57, 58)-(3782, 2018); sharp 2800 px wide, soft = Gaussian sigma 6 px, 1400 px wide.\n"
        f"export const CHIP_ASPECT = {aspect:.6f};\n"
        f"export const CHIP_SRC_W = {W};\n"
        f"export const CHIP_SOFT_SIGMA = {SOFT_SIGMA};\n"
        f'export const CHIP_SHARP = "data:image/jpeg;base64,{base64.b64encode(a).decode()}";\n'
        f'export const CHIP_SOFT = "data:image/jpeg;base64,{base64.b64encode(b).decode()}";\n'
    )
print(f"sharp {W}x{H} {len(a) / 1e6:.2f} MB, soft {soft.width}x{soft.height} {len(b) / 1e6:.2f} MB, aspect {aspect:.4f}")
