const inLand = (lon, lat) => geoContains(land, [lon, lat]);
const bbox = (geom) => {
  let x0 = 180;
  let x1 = -180;
  let y0 = 90;
  let y1 = -90;
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates;
  for (const p of polys)
    for (const [x, y] of p[0]) {
      x0 = Math.min(x0, x);
      x1 = Math.max(x1, x);
      y0 = Math.min(y0, y);
      y1 = Math.max(y1, y);
    }
  return { x0, x1, y0, y1 };
};
const countryOf = (lon, lat) => countries.find((c) => geoContains(c, [lon, lat]));

const out = [];
const push = (lon, lat, w) => out.push([lon, lat, Math.max(0.05, Math.min(1, w))]);

// 1. the metro clusters: n ~ pop^0.75, a gaussian of sigma 0.06 + 0.045 sqrt(pop) deg, brighter at the core
const CITY_C = 5.6;
let nCity = 0;
for (const [lon, lat, pop] of CITIES) {
  if (!inLand(lon, lat)) continue; // islands missing at 1:110m (Singapore): their light falls in the sea, skip
  const n = Math.max(3, Math.round(CITY_C * Math.pow(pop, 0.75)));
  const sig = 0.06 + 0.045 * Math.sqrt(pop);
  const cosl = Math.max(0.2, Math.cos((lat * Math.PI) / 180));
  for (let i = 0; i < n; i++) {
    for (let tries = 0; tries < 8; tries++) {
      const r = Math.abs(gauss());
      const a = rnd() * 2 * Math.PI;
      const dl = (sig * r * Math.cos(a)) / cosl;
      const dp = sig * r * Math.sin(a);
      const x = lon + dl;
      const y = lat + dp;
      if (!inLand(x, y)) continue;
      const core = Math.exp(-0.5 * r * r);
      push(x, y, 0.45 + 0.35 * core + 0.2 * Math.min(1, pop / 15) * core + 0.08 * (rnd() - 0.5));
      nCity++;
      break;
    }
  }
}

// 2. the national scatter: towns and villages, n ~ the country's population; a share uniform over the country, the
// rest round its own listed cities (wide), so deserts and tundra stay dark
const RURAL_PER_M = 1.15;
let nRural = 0;
const citiesByCountry = new Map();
for (const c of CITIES) {
  const co = countryOf(c[0], c[1]);
  if (!co) continue;
  if (!citiesByCountry.has(co.id)) citiesByCountry.set(co.id, []);
  citiesByCountry.get(co.id).push(c);
}
for (const co of countries) {
  const spec = POP[co.id];
  if (!spec) continue;
  const [pop, uni] = spec;
  const n = Math.round(RURAL_PER_M * Math.pow(pop, 0.92));
  if (n <= 0) continue;
  const bb = bbox(co.geometry);
  const mine = citiesByCountry.get(co.id) ?? [];
  const totalW = mine.reduce((s, c) => s + Math.sqrt(c[2]), 0);
  for (let i = 0; i < n; i++) {
    const uniform = mine.length === 0 || rnd() < uni;
    for (let tries = 0; tries < 40; tries++) {
      let x;
      let y;
      if (uniform) {
        x = bb.x0 + rnd() * (bb.x1 - bb.x0);
        y = bb.y0 + rnd() * (bb.y1 - bb.y0);
      } else {
        let pick = rnd() * totalW;
        let c = mine[0];
        for (const m of mine) {
          pick -= Math.sqrt(m[2]);
          if (pick <= 0) {
            c = m;
            break;
          }
        }
        const sig = 1.1 + 0.25 * Math.sqrt(c[2]);
        const cosl = Math.max(0.2, Math.cos((c[1] * Math.PI) / 180));
        x = c[0] + (sig * gauss()) / cosl;
        y = c[1] + sig * gauss();
      }
      if (!geoContains(co, [x, y])) continue;
      push(x, y, 0.22 + 0.22 * rnd());
      nRural++;
      break;
    }
  }
}

out.sort((a, b) => a[2] - b[2]);
const buf = new Uint8Array(out.length * 5);
