// Bakes the outlines of "$400M" in Söhne Dreiviertelfett (public/Sohne-Dreiviertelfett.otf, the Cheeky Pint numeral
// face FONT_NUM) into generated/components/scott-aircraft-order/fourHundredGlyphs.ts, for ListForFourHundredMillion's
// extruded 3D type (THREE.Shape -> ExtrudeGeometry). Parser: opentype.js as shipped inside three
// (three/examples/jsm/libs/opentype.module.js); nothing installed.
// Run: bun scripts/clips/scott-aircraft-order/bake-400m-glyphs.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
// @ts-expect-error untyped module
import opentype from "three/examples/jsm/libs/opentype.module.js";

const ROOT = join(import.meta.dir, "../../..");
const TEXT = "$400M";
const buf = readFileSync(join(ROOT, "public/Sohne-Dreiviertelfett.otf"));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const upm: number = font.unitsPerEm;
// one path per glyph, in em units, y UP, x from the string's start (kerning on)
const glyphs = font.stringToGlyphs(TEXT);
let x = 0;
const out: { ch: string; x: number; adv: number; cmds: (string | number)[][] }[] = [];
for (let i = 0; i < glyphs.length; i++) {
  const g = glyphs[i];
  const cmds: (string | number)[][] = [];
  for (const c of g.path.commands) {
    const P = (px: number, py: number) => [+(px / upm).toFixed(5), +(py / upm).toFixed(5)];
    if (c.type === "M" || c.type === "L") cmds.push([c.type, ...P(c.x, c.y)]);
    else if (c.type === "Q") cmds.push(["Q", ...P(c.x1, c.y1), ...P(c.x, c.y)]);
    else if (c.type === "C") cmds.push(["C", ...P(c.x1, c.y1), ...P(c.x2, c.y2), ...P(c.x, c.y)]);
    else if (c.type === "Z") cmds.push(["Z"]);
  }
  out.push({ ch: TEXT[i], x: +(x / upm).toFixed(5), adv: +(g.advanceWidth / upm).toFixed(5), cmds });
  x += g.advanceWidth;
  if (i < glyphs.length - 1) x += font.getKerningValue(g, glyphs[i + 1]);
}
const capH = font.tables.os2?.sCapHeight ? font.tables.os2.sCapHeight / upm : 0.7;
const src = `// GENERATED by scripts/clips/scott-aircraft-order/bake-400m-glyphs.ts from public/Sohne-Dreiviertelfett.otf: do not edit.
// "${TEXT}" glyph outlines in em units (y up, x from the string start, kerning applied). Commands: M/L x y, Q x1 y1 x y,
// C x1 y1 x2 y2 x y, Z (the font's own contour winding).
export type GlyphCmd = (string | number)[];
export const FOUR_HUNDRED = {
  text: ${JSON.stringify(TEXT)},
  width: ${+(x / upm).toFixed(5)},
  capHeight: ${+capH.toFixed(5)},
  glyphs: ${JSON.stringify(out)} as { ch: string; x: number; adv: number; cmds: GlyphCmd[] }[],
} as const;
`;
writeFileSync(join(ROOT, "generated/components/scott-aircraft-order/fourHundredGlyphs.ts"), src);
console.log(`baked ${TEXT}: width ${(x / upm).toFixed(3)} em, cap ${capH.toFixed(3)} em, ${out.map((g) => `${g.ch}:${g.cmds.length}`).join(" ")}`);
