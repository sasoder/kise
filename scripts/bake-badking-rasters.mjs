// Bakes the STATIC layers of THE INDIAN SUBCONTINENT c. 1756 (sea, 4 engraved
// water-lines, 5 deg graticule, land + hand-coloured rim, cream coast; NO
// borders of any kind: the modern ones did not exist and we hold no period
// data) into tiled rasters for the cut SoonerOrLaterABadKing, so a frame draws
// a few 2048-texel tiles instead of re-rasterising the 10m vectors.
//
//   bun scripts/bake-badking-rasters.mjs
//
// Needs generated/components/SoonerOrLaterABadKingStatic.ts
// (scripts/build-badking-map.mjs). Writes public/badking/<level>-<i>-<j>.png
// and generated/components/SoonerOrLaterABadKingLevels.ts.
//
// TWO levels (the cut runs k 1.0 ... 4.35):
//   base   the whole subcontinent (the wide frame + sway, and the opening in the north), s = 2.2 texels per
//          world px: sharp to k ~2.3; strokes drawn for k 1.3
//   bengal the north-east the camera pushes into, s = 4.5: sharp to k ~4.7;
//          strokes drawn for k 3.4; fades in over k 1.7 ... 2.2 (band), and
//          only where the frame lies inside its rect

import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { Resvg } from "@resvg/resvg-js";
import { GRATICULE_D, LAND_D, LAND_WL_D } from "../generated/components/SoonerOrLaterABadKingStatic.ts";

const OUT_DIR = "public/badking";
const OUT_TS = "generated/components/SoonerOrLaterABadKingLevels.ts";
const TILE = 2048;
const APRON = 2;

const SEA = "#1B2226";
const LAND = "#3F3428";
const LAND_RIM = "#6A5838";
const INK = "#E9DDBF";

export const LEVEL_DEF = [
  { name: "base", kBake: 1.3, s: 2.2, band: null, rect: { x0: -130, x1: 1210, y0: -330, y1: 1990 } },
  { name: "bengal", kBake: 3.4, s: 4.5, band: [1.7, 2.2], rect: { x0: 380, x1: 1210, y0: 180, y1: 1420 } },
];

const mix = (a, b, t) => {
  const pa = [1, 3, 5].map((i) => parseInt(a.slice(i, i + 2), 16));
  const pb = [1, 3, 5].map((i) => parseInt(b.slice(i, i + 2), 16));
  return `rgb(${pa.map((v, i) => Math.round(v + (pb[i] - v) * t)).join(",")})`;
};
const stack = (kB) => {
  const px = (v) => v / kB;
  const wlGap = 6.5 * Math.pow(kB, 0.45);
  const wlOp = [0.3, 0.2, 0.12, 0.065];
  let wl = "";
  for (let i = 3; i >= 0; i--) {
    const d = wlGap * (i + 1);
    wl += `<path d="${LAND_WL_D}" fill="none" stroke="${mix(SEA, INK, wlOp[i])}" stroke-width="${px(2 * d + 1.15)}" stroke-linejoin="round"/>`;
    wl += `<path d="${LAND_WL_D}" fill="none" stroke="${SEA}" stroke-width="${px(2 * d - 1.15)}" stroke-linejoin="round"/>`;
  }
  return `
<defs><clipPath id="land"><path d="${LAND_D}" clip-rule="evenodd"/></clipPath></defs>
<rect x="-5000" y="-5000" width="12000" height="14000" fill="${SEA}"/>
${wl}
<path d="${GRATICULE_D}" fill="none" stroke="${INK}" stroke-opacity="0.12" stroke-width="${px(1.2)}"/>
<path d="${LAND_D}" fill="${LAND}" fill-rule="evenodd"/>
<g clip-path="url(#land)">
  <path d="${LAND_D}" fill="none" stroke="${LAND_RIM}" stroke-opacity="0.2" stroke-width="${px(28)}" stroke-linejoin="round"/>
  <path d="${LAND_D}" fill="none" stroke="${LAND_RIM}" stroke-opacity="0.28" stroke-width="${px(10)}" stroke-linejoin="round"/>
  <path d="${GRATICULE_D}" fill="none" stroke="${INK}" stroke-opacity="0.07" stroke-width="${px(1.2)}"/>
</g>
<path d="${LAND_D}" fill="none" stroke="${INK}" stroke-opacity="0.82" stroke-width="${px(1.5)}" stroke-linejoin="round"/>`;
};

mkdirSync(OUT_DIR, { recursive: true });
for (const f of readdirSync(OUT_DIR)) if (f.endsWith(".png")) rmSync(`${OUT_DIR}/${f}`);
const levels = [];
for (const L of LEVEL_DEF) {
  const r = L.rect;
  const W = Math.ceil((r.x1 - r.x0) * L.s);
  const H = Math.ceil((r.y1 - r.y0) * L.s);
  const nx = Math.ceil(W / TILE);
  const ny = Math.ceil(H / TILE);
  const tiles = [];
  let bytes = 0;
  const t0 = Date.now();
  for (let j = 0; j < ny; j++)
    for (let i = 0; i < nx; i++) {
      const tx = i * TILE;
      const ty = j * TILE;
      const TW = Math.min(W, tx + TILE + APRON) - tx;
      const TH = Math.min(H, ty + TILE + APRON) - ty;
      const file = `${L.name}-${i}-${j}.png`;
      const tile = { f: file, x0: r.x0 + tx / L.s, y0: r.y0 + ty / L.s, w: TW / L.s, h: TH / L.s, W: TW, H: TH };
      tiles.push(tile);
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${TW}" height="${TH}" viewBox="${tile.x0} ${tile.y0} ${tile.w} ${tile.h}">${stack(L.kBake)}</svg>`;
      const png = new Resvg(svg, { fitTo: { mode: "original" }, shapeRendering: 2 }).render().asPng();
      writeFileSync(`${OUT_DIR}/${file}`, png);
      bytes += png.length;
    }
  console.log(`${L.name}: ${W}x${H} texels, ${nx}x${ny} tiles, ${(bytes / 1e6).toFixed(2)} MB, ${((Date.now() - t0) / 1000).toFixed(1)} s`);
  levels.push({ name: L.name, kBake: L.kBake, s: L.s, band: L.band, x0: r.x0, y0: r.y0, w: W / L.s, h: H / L.s, W, H, tiles });
}
writeFileSync(
  OUT_TS,
  `// Generated by scripts/bake-badking-rasters.mjs — do not edit by hand.
// The static map of the Indian subcontinent as tiled rasters (public/badking/<f>): the level's
// world rect (x0, y0, w, h in world px), its bake zoom kBake, its texels per
// world px s, and its tiles (world rect + texel size; neighbours overlap by
// ${APRON} texels on the right / bottom).
export type Tile = { f: string; x0: number; y0: number; w: number; h: number; W: number; H: number };
export type Level = { name: string; kBake: number; s: number; band: [number, number] | null; x0: number; y0: number; w: number; h: number; W: number; H: number; tiles: Tile[] };
export const LEVELS: Level[] = ${JSON.stringify(levels, null, 1)};
`,
);
console.log(`Wrote ${OUT_TS}`);
