import React from 'react';
import {AbsoluteFill, interpolate, spring, useCurrentFrame} from 'remotion';

export type GeneratedSceneProps = {
  title?: string;
  subtitle?: string;
  accent?: string;
};

const pillStyle = (accent: string): React.CSSProperties => ({
  display: 'inline-block',
  padding: '10px 18px',
  borderRadius: 999,
  fontSize: 24,
  color: '#08111f',
  background: accent,
  fontWeight: 700,
  marginBottom: 24,
});

export const GeneratedScene: React.FC<GeneratedSceneProps> = ({
  title = 'Hello world',
  subtitle = 'Generated by the agent',
  accent = '#7dd3fc',
}) => {
  const frame = useCurrentFrame();
  const s = spring({frame, fps: 30, config: {damping: 200}});

  return (
    <AbsoluteFill
      style={{
        background: 'linear-gradient(135deg, #0b1020, #172554)',
        color: 'white',
        justifyContent: 'center',
        alignItems: 'center',
        fontFamily: 'Inter, ui-sans-serif, system-ui, sans-serif',
      }}
    >
      <div
        style={{
          textAlign: 'center',
          transform: `translateY(${interpolate(s, [0, 1], [40, 0])}px) scale(${interpolate(s, [0, 1], [0.97, 1])})`,
          opacity: s,
        }}
      >
        <div style={pillStyle(accent)}>Market report</div>
        <div style={{fontSize: 92, fontWeight: 800, marginBottom: 20}}>{title}</div>
        <div style={{fontSize: 34, opacity: 0.85}}>{subtitle}</div>
      </div>
    </AbsoluteFill>
  );
};

export default GeneratedScene;
