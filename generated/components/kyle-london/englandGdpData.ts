/** decade means of the annual series: [mid-decade year, mean of the ten annual values], 1650-59 ... 1890-99 */
export const ENGLAND_GDP_DECADE_MEANS: readonly (readonly [number, number])[] = (() => {
  const out: [number, number][] = [];
  for (let d = GDP_FIRST_YEAR; d + 9 < GDP_LAST_YEAR; d += 10) {
    let s = 0;
    for (let y = d; y < d + 10; y++) s += ENGLAND_GDP_PER_HEAD[y - GDP_FIRST_YEAR];
    out.push([d + 4.5, s / 10]);
  }
  return out;
})();
